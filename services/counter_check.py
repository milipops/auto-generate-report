# Все формы записи ОБЩЕГО счётчика у мастеров: «Общ.сч. -750733»,
# «Об. Сч.: 284387», «Сч 760449», «Общ сч21431800». Подчёркивания бланка
# («_766068__») обязательны — ими мастера заполняют пустые клетки.
#
# ВАЖНО: «сч» встречается и у СРЕДНЕГО/СРЕЗОВОГО счётчика — «Ср. Сч.: 4274 из
# 14800», «Ср сч.: 1553 из 14800», «Срез.сч. 750 из 760», «Срезовой 656 из 750».
# Раньше ветка «\bсч» ловила их все, потому что перед «Сч.» стоит граница слова.
# Последствие (прогон 15.09.2026, ст.251): валидатор насчитал «12 значений по 4
# цифры» — это были средние счётчики — и «исправил» честные показания общего
# счётчика 288402 → 4274 и 291916 → 7788. Испорченные числа ушли в отчёт
# («Показания счетчика, узл.» в листе 15.09) И в counter_ledger.json, отравив
# перенос на следующую смену. Поэтому перед «сч» обязателен отрицательный
# просмотр на «ср»/«средн»/«срез»/«срезн»/«срезов».
_NOT_AVERAGE_RE = r"(?<![а-яё.\s])(?<!ср)(?<!средн)(?<!срез)(?<!срезн)(?<!срезов)"
# Разделители между «сч» и числом идут В ПРОИЗВОЛЬНОМ порядке и количестве:
# мастера пишут «Общ.сч. -750733», «Об. Сч.: 284387», «Об. Сч:. 291916»,
# «Сч:- 123456». Раньше шаблон ждал строго «точка, потом двоеточие», и запись
# «Об. Сч:. 291916» (прогон 15.09.2026, ст.251) не находилась — валидатор не
# увидел честное конечное показание и «исправил» его на 291798, ближайшее из
# найденных. Поэтому здесь просто класс разделителей со звёздочкой.
#
# Звёздочка в классе — разметка выгрузки: мастер выделяет бланк жирным, и
# метка закрывается раньше числа — «**Общ.сч**. -____228935__» (прогон
# 27.09.2026, ст.111). Без неё число темы не находилось, и правило 1 объявляло
# честное начало смены «отличающимся от остальных за смену».
#
# Второй класс — слова между меткой и числом у наладчиков: «Об.сч. на начало
# -303371 Об.сч на конец- 303389», «Об.сч по окончанию-228953» (прогоны
# 26.–27.09.2026). Без них показание наладчика не попадало в «достоверные», и
# честное число разбор назывался «отличается от остальных за смену».
#
# Слово должно быть ИЗ СПИСКА (иначе «сч.» начал бы ловить любое следующее
# число в сообщении), а разделители стоят и ДО него, и после: «Об.сч. на
# начало» — точка после метки обязательна, иначе форма не читается.
_SEP = r"[\s.:;\-–—_*]"
_WORD = (r"(?:на|по|за|до|после|перед|начал[а-яё]*|конц[а-яё]*|"
         r"окончан[а-яё]*|итог[а-яё]*|утр[а-яё]*|вечер[а-яё]*)")
_COUNTER_RE = re.compile(
    r"(?:общ\s*[а-яё]*\.?\s*сч|об\.?\s*сч|\bсч)[а-яё]*"
    + _SEP + r"*"
    + r"(?:" + _WORD + _SEP + r"+)?"
    + r"(?:" + _WORD + _SEP + r"+)?"
    + _SEP + r"*(\d{4,9})", re.IGNORECASE)
# Отдельно отсекаем записи, где перед «сч» стоит признак среднего/срезового.
_AVERAGE_RE = re.compile(
    r"(?:ср|средн|срез|срезн|срезов|со)[а-яё]*\.?\s*сч", re.IGNORECASE)
# «1000 из 1450» — это счётчик ОДНОГО СРЕЗА (1450 — узлов в срезе), а не общий
# счётчик станка. Структурный признак надёжнее сокращения: мастер пишет то
# «Со.сч.», то «Срез. Сч», то «Ср. Сч», но «N из <размер среза>» — всегда.
_SLICE_PAIR_RE = re.compile(r"^\s*(?:из|[a-zа-яё]{1,4}\s*из)\s*\d", re.IGNORECASE)

# Запас к физическому пределу выпуска: норма в справочнике округлена.
_RATE_SAFETY = 1.5
# Насколько начало смены может отличаться от конца прошлой смены.
_LEDGER_TOLERANCE = 5000
# Число под вопросом — просим мастера подтвердить. Реплика держится здесь, а
# не в day_pipeline: только тут известно, какая заметка сомнение, а какая
# просто объясняет выбор (правило 0 про начало смены).
_ASK_FIX = " Если число верное — пришлите исправленное показание счётчика."


def _as_int(value):
    """Целое, если значение целое: 120796, а не 120796.0.

    Показания счётчика — это номер узла, дробей в нём не бывает. Float уходит в
    counter_ledger.json и печатается в Excel («перенос с прошлой смены
    120796.0»), поэтому целые значения возвращаем int.
    """
    try:
        f = float(value)
    except (TypeError, ValueError):
        return value
    return int(f) if f.is_integer() else f


def _counter_matches(text: str) -> List["re.Match"]:
    """Позиции показаний ОБЩЕГО счётчика в тексте, по порядку следования.

    Средние/срезовые счётчики («Ср. Сч.: 4274 из 14800», «Со.сч.1000 из 1450»)
    отбрасываются: они на порядок меньше общих, и если их смешать, модальная
    длина числа укажет на них как на «правильные», а настоящие показания
    объявит опечаткой.
    """
    out: List[re.Match] = []
    for m in _COUNTER_RE.finditer(text or ""):
        # Смотрим, что стоит ПЕРЕД найденным «сч»: если там «ср.»/«срез.» —
        # это средний счётчик, пропускаем.
        # Берём с запасом ВКЛЮЧАЯ само «сч» (+3), иначе _AVERAGE_RE не найдёт
        # шаблон «ср…сч»: срез до m.start()+1 обрывался на «Ср. С».
        prefix = (text or "")[max(0, m.start() - 9):m.start() + 3]
        if _AVERAGE_RE.search(prefix):
            continue
        # «… 1000 из 1450» — узлов внутри одного среза, а не показание станка.
        if _SLICE_PAIR_RE.match((text or "")[m.end():m.end() + 14]):
            continue
        try:
            int(m.group(1))
        except (TypeError, ValueError):
            continue
        out.append(m)
    return out


def _find_counters(text: str) -> List[int]:
    """Все показания ОБЩЕГО счётчика из текста — по порядку следования."""
    return [int(m.group(1)) for m in _counter_matches(text)]


# Подпись сообщения в тексте раздела переписки: «Белякова С., 06:53: …».
_MSG_SIG_RE = re.compile(
    r"^([А-ЯЁ][а-яё.]{1,}(?:\s+[А-ЯЁ][а-яё.]{1,}){0,3}),\s*"
    r"(\d{1,2})[:.](\d{2})\s*:", re.MULTILINE)

# Кто оператор станка, прямо написано в заголовке раздела:
# «98 машина(Белякова) - информация за смену 21.09.2026г. 06:26».
_SECTION_OPERATOR_RE = re.compile(
    r"(?:^|[^\d])(\d{2,4})\s*машина\s*\(\s*([^)]{2,40}?)\s*\)", re.IGNORECASE)


def _same_author(name: str, operator: str) -> bool:
    """Один ли человек: «Белякова С.» из подписи и «Белякова» из заголовка."""
    def tokens(s: str) -> set:
        return {t.strip(" .,()").lower() for t in str(s or "").split()
                if len(t.strip(" .,()")) > 1}

    return bool(tokens(name) & tokens(operator))


def section_operator(text: str) -> str:
    """Фамилия оператора станка из заголовка раздела ('' — если не написано)."""
    m = _SECTION_OPERATOR_RE.search(text or "")
    return m.group(2).strip() if m else ""


def counter_readings(text: str) -> List[Tuple[Optional[int], str, int]]:
    """Показания общего счётчика в порядке переписки: [(минута, автор, число)].

    Порядок сообщений = хронология смены, поэтому «первое» и «последнее»
    показания берутся отсюда, а не угадываются по длине числа. Минута и автор
    нужны, чтобы отличить начало СВОЕЙ смены от состояния, которое принёс
    мастер утренней сводкой.
    """
    sigs = [(m.start(), m.group(1), int(m.group(2)) * 60 + int(m.group(3)))
            for m in _MSG_SIG_RE.finditer(text or "")]
    out: List[Tuple[Optional[int], str, int]] = []
    for m in _counter_matches(text):
        author, minute = "", None
        for pos, name, mins in sigs:
            if pos > m.start():
                break
            author, minute = name, mins
        out.append((minute, author, int(m.group(1))))
    return out


def _modal_length(values: List[int]) -> Optional[int]:
    """Самая частая длина числа в разрядах. None, если доверять нечему."""
    if len(values) < 3:
        return None
    counts: Dict[int, int] = {}
    for v in values:
        key = len(str(abs(v)))
        counts[key] = counts.get(key, 0) + 1
    best = max(counts.items(), key=lambda kv: (kv[1], -kv[0]))
    # Модалем доверяем, только если он явно главный: минимум два значения
    # такой длины и строго больше, чем у любой другой длины.
    if best[1] < 2:
        return None
    others = [c for k, c in counts.items() if k != best[0]]
    if others and best[1] <= max(others):
        return None
    return best[0]


def _drop_one_digit(value: int, good: List[int],
                    lo: Optional[float], hi: Optional[float]) -> Optional[int]:
    """Вычеркнуть из числа ЛИШНЮЮ ЦИФРУ и проверить результат монотонностью.

    Опечатка мастера почти всегда — одна лишняя цифра: «7760351» вместо
    «760351», «1200807» вместо «120807». Просто взять соседнее показание смены
    нельзя — это другое измерение, и часы выходят иные. Проверено на эталоне
    пользователя (14.09, ст.151): восстановление 7760351 → 760351 даёт ровно
    его 8,7 ч, а подстановка следующего показания 760449 — 8,59 ч.

    Вычёркивание одной цифры даёт несколько кандидатов (7760351 → 760351,
    770351, 776031, …), поэтому отбираем их РЕШАЮЩИМ признаком: счётчик за
    смену только РАСТЁТ.

        lo..hi — допустимый коридор для восстанавливаемого значения:
          * для НАЧАЛЬНОГО показания: от конечного прошлой смены до первого
            показания этой смены (7760351 → 760351 ≤ 760449 ✓, 770351 ✗);
          * для КОНЕЧНОГО: от последнего показания смены до «последнее +
            выпуск за смену» (1200807 → 120807 ≥ 120796 ✓, 120087 ✗).

    Возвращаем кандидата только если он ЕДИНСТВЕННЫЙ в коридоре: при нескольких
    вариантах доказательств недостаточно, и число лучше оставить как есть.
    """
    if not good:
        return None
    digits = str(abs(int(value)))
    target = len(str(abs(good[-1])))
    sign = 1 if value >= 0 else -1
    seen = set()
    for i in range(len(digits)):
        cand_s = digits[:i] + digits[i + 1:]
        if len(cand_s) != target or not cand_s:
            continue
        cand = int(cand_s) * sign
        if lo is not None and cand < lo:
            continue
        if hi is not None and cand > hi:
            continue
        seen.add(cand)
    return seen.pop() if len(seen) == 1 else None


def max_output(machine: str) -> Optional[float]:
    """Физический предел выпуска за смену (узлов) по норме станка.

    Публичное имя: нужен не только здесь, но и переносу счётчика в
    day_pipeline («влезает ли разница в одну смену»).
    """
    rate = machine_rates.get_rate(machine)
    if not rate:
        return None
    return rate * 60.0 * MACHINE_SHIFT_HOURS * _RATE_SAFETY


def check_counters(machine: str,
                   start: Optional[float],
                   end: Optional[float],
                   text: str = "",
                   prev_end: Optional[float] = None,
                   prev_is_adjacent: bool = False,
                   operator: Optional[str] = None) -> Tuple[
                       Optional[float], Optional[float], List[str]]:
    """Проверить пару показаний и вернуть (start, end, заметки).

    Возвращает ИСХОДНЫЕ значения, если подозрений нет или доказательств
    недостаточно. Заметки — готовые строки для предупреждения пользователю:
    он должен видеть, что число исправлено и почему.
    """
    notes: List[str] = []
    values = _find_counters(text)
    modal = _modal_length(values)
    good = ([v for v in values if len(str(abs(v))) == modal]
            if modal else [])

    # 0. ГРАНИЦА СМЕНЫ — самое РАНОЕ по переписке показание, записанное в теме
    # станка. Тему открывает передача смены: «111 машина(Арташина Т)» и
    # «**Общ.сч**. -____228935__» в 19:34 накануне. Это то состояние, с которым
    # станок достался оператору, и именно от него считает наработку пользователь
    # в своём ручном отчёте за 27.09.2026: ст.111 — 228935 → 234542 = 5607 узлов
    # = 6,148 ч; ст.321 — 125370 → 126174 = 804 узла (не 125369 из записки
    # наладчика про его окно, а именно передача смены).
    #
    # Раньше правило сдвигало начало ВПЕРЁД на первое показание оператора
    # всегда. Прогон 27.09.2026, ст.111: Арташина записала счётчик впервые только
    # в 07:36 («Об. Сч. 229094»), начало уехало с 228935 на 229094 — минус 159
    # узлов (0,18 ч) РАБОТЫ станка, и в отчёте вырос «оператор −0,9 ч». Эти 159
    # узлов станок наработал честно, между сводкой мастера и записью оператора.
    #
    # Вперёд начало отодвигается только там, где раннее показание физически не
    # может быть состоянием перед сменой: выпуск от него до конца смены больше
    # предельного для станка. Прогон 21.09.2026, ст.98: сводка Черныш 06:38 —
    # 21486750, вечерний итог 21509000 -> 22 250 узлов = 20,6 ч при смене в 12 ч
    # (предел станка 19 440). Верно только 21497900 — первое показание Беляковой.
    #
    # Начало трогаем, только когда оно само похоже на честное показание (длина
    # числа как у остальных за смену). Испорченное опечаткой начало («7760351»
    # за 14.09, ст.151) лечит правило 1 — оно вычёркивает лишнюю цифру и
    # проверяет кандидата монотонностью, а не берёт первое число темы.
    # Рассогласованную пару (начало ≥ конца) не трогаем вовсе: прогон 26.09.2026,
    # ст.251 — «391938» утром (опечатка в 301938, той же длины) и 303370 вечером;
    # первое показание темы придвинуло бы начало к концу и съело выпуск. Такую
    # пару лечат правила 4 и 5 — по журналу станка.
    readings = [(t, a, v) for t, a, v in counter_readings(text)
                if modal is None or len(str(abs(v))) == modal]
    # Начало уже подняли с устаревшей сводки мастера к записи оператора — назад
    # к этой сводке возвращать нельзя (21.09.2026, ст.98).
    raised_to_operator = False

    def boundary_now() -> None:
        """Отпустить/поднять начало смены до границы по теме (правило 0).

        Вызывается ДО правил 1–5 и ПОСЛЕ них: чистка потерянного вечера
        (правило 4) делает пару согласованной, и только после этого начало
        можно отпустить к передаче смены (прогон 27.09.2026, ст.251 — разбор
        отдал «303371 → 303370», границу 303370 видно лишь после того, как
        конец стал 304335).
        """
        nonlocal start, raised_to_operator
        if start is None or not readings:
            return
        # Начало с опечаткой (длина числа не как у остальных) — к правилу 1.
        if modal is not None and len(str(abs(int(start)))) != modal:
            return
        # Рассогласованную пару лечат правила 4 и 5, а не граница смены.
        if end is not None and int(start) >= int(end):
            return
        limit = max_output(machine) or 0.0

        def opens_shift(value: int) -> bool:
            """Годится ли показание в начало смены: ниже конца и сдвиг реален."""
            if end is not None and value >= int(end):
                return False
            if limit:
                # Выпуск от кандидата до конца смены — в пределах смены.
                if end is not None and int(end) - value > limit:
                    return False
                # И шаг НАЗАД не больше наработки за смену.
                if value < int(start) and int(start) - value > limit:
                    return False
            return True

        boundary = None
        boundary_from_operator = False
        first = readings[0][2]
        if opens_shift(start) and first < int(start) and not raised_to_operator:
            # Начало уже честное — назад отпускаем только к передаче смены.
            boundary = first
        elif not opens_shift(start):
            # Раннее показание темы не влезает в смену: это состояние СТАРШЕ
            # смены, границу берём у оператора.
            own = [v for _t, a, v in readings
                   if a and operator and _same_author(a, str(operator))]
            if own and own[0] > int(start) and opens_shift(own[0]):
                boundary = own[0]
                boundary_from_operator = True
            else:
                # Прогон 28.09.2026, ст.98: утром мастер передал ВЧЕРАШНЮЮ пару
                # показаний («Общ. Сч 21563900» и «Сч 21574050» — оба с 27.09),
                # а Елистратова своё начало записала словами «7.00 начало работы
                # … Ср.сч. 21574050». Метка «Ср.сч.» — срезовой счётчик, общим
                # он не читается, поэтому показания самого оператора в теме не
                # осталось. Начало берём самым РАННИМ показанием этой же темы, от
                # которого выпуск влезает в смену: число стоит в переписке, его
                # никто не выдумывает, а старое начало уже доказанно невозможно.
                fitting = [v for _t, _a, v in readings
                           if int(start) < v < (int(end) if end is not None
                                                else 1 << 62)
                           and opens_shift(int(v))]
                if fitting:
                    boundary = min(fitting)
        if boundary is not None and int(start) != boundary:
            if boundary < int(start):
                notes.append(
                    f"№{machine}: начало смены {int(start)} сдвинуто назад на "
                    f"{boundary} — это самое раннее показание, записанное в "
                    f"теме станка (передача смены), от него и считаем выпуск")
            elif boundary_from_operator:
                notes.append(
                    f"№{machine}: начальное показание {int(start)} — из "
                    f"утренней сводки мастера (состояние до начала смены), "
                    f"взято первое показание оператора {boundary}")
                raised_to_operator = True
            else:
                notes.append(
                    f"№{machine}: начало смены {int(start)} — вчерашнее "
                    f"показание из утренней передачи: от него станок "
                    f"наработал бы больше, чем физически успевает за смену. "
                    f"Взято {boundary} — это показание записано в этой "
                    f"же теме, выпуск считан от него." + _ASK_FIX)
                raised_to_operator = True
            start = float(boundary)

    boundary_now()

    # 1. Выброс по длине числа: берём крайние из «правильных» значений.
    if good and len(good) >= 2:
        limit = max_output(machine) or 0.0
        # Коридор монотонности: счётчик за смену только растёт.
        # Начало — от прошлой смены (prev_end) до первого показания этой;
        # конец — от последнего показания смены до «последнее + выпуск».
        # Верхняя граница для start — ПЕРВОЕ ДОСТОВЕРНОЕ показание смены,
        # а не само проверяемое число: иначе испорченное «7760351» расширяло
        # коридор до себя и пропускало лишнего кандидата (770351 рядом с
        # 760351), из-за чего №151 за 14.09 не восстанавливался.
        corridors = {
            "start": (prev_end if prev_end is not None else min(good) - limit,
                      min(good)),
            "end": (max(good), max(good) + limit),
        }
        for attr in ("start", "end"):
            value = start if attr == "start" else end
            if value is None or int(value) in good:
                continue
            lo, hi = corridors[attr]
            restored = _drop_one_digit(int(value), good, lo, hi)
            if restored is None:
                # Какую цифру вычеркнуть — неизвестно. Число остаётся КАК
                # НАПИСАНО: подставить вместо него соседнее показание — значит
                # молча нарисовать в отчёте часы, которых не было, и испортить
                # перенос на следующую смену (21.09.2026, ст.98: 21509000 ->
                # 21501650 уехало в counter_ledger.json).
                notes.append(
                    f"№{machine}: {('начальное' if attr == 'start' else 'конечное')} "
                    f"показание {int(value)} отличается от остальных за смену "
                    f"({len(good)} значений по {modal} цифр). Какую цифру "
                    f"вычеркнуть — неясно, число оставлено как написано."
                    + _ASK_FIX)
                continue
            notes.append(
                f"№{machine}: {('начальное' if attr == 'start' else 'конечное')} "
                f"показание {int(value)} не похоже на остальные за смену "
                f"({len(good)} значений по {modal} цифр) — вероятна опечатка, "
                f"восстановлено вычёркиванием лишней цифры: {restored}"
                + _ASK_FIX)
            if attr == "start":
                start = float(restored)
            else:
                end = float(restored)

    # 2. Дельта больше, чем станок физически мог выдать за смену.
    limit = max_output(machine)
    if limit and start is not None and end is not None:
        delta = end - start
        if delta > limit:
            rate = machine_rates.get_rate(machine)
            notes.append(
                f"№{machine}: по показаниям {int(start)} -> {int(end)} "
                f"выпуск {int(delta)} узлов = "
                f"{delta / (rate * 60):.0f} ч работы — больше смены в "
                f"{MACHINE_SHIFT_HOURS:.0f} ч. В показании опечатка, "
                f"проверьте счётчик станка {machine}." + _ASK_FIX)

    # 3. Сверка с прошлой сменой (counter_ledger). Работает ТОЛЬКО если это
    # действительно соседняя смена (не дальше 2 дней): в журнале бывают
    # пропуски, и сравнение 14.09 с 10.09 давало ложную тревогу на ст.98 —
    # за четыре дня станок legitimately нарабатывает больше одной смены.
    #
    # И не срабатывает, если подозрительное значение мастер повторил 2+ раза:
    # независимые записи одного и того же числа — это доказательство, что
    # счётчик действительно такой (его заменили/обнулили). Прогон 15.09.2026,
    # ст.321: «Общ сч 1200807» написано трижды (06:55, 07:05 и в конце смены),
    # и пользователь принял его в своём отчёте как начало и конец с нулевым
    # выпуском, а правило 3 каждый прогон выдавало тревогу про опечатку.
    repeated = (values.count(int(start)) >= 2) if start is not None else False
    if prev_end is not None and start is not None and prev_is_adjacent \
            and not repeated:
        if abs(start - prev_end) > max(_LEDGER_TOLERANCE, limit or 0):
            notes.append(
                f"№{machine}: начальное показание {int(start)} отличается "
                f"от конечного за прошлую смену ({int(prev_end)}) больше, "
                f"чем станок мог наработать за смену. Проверьте, не "
                f"опечатка ли это." + _ASK_FIX)

    # 4. КОНЕЦ СМЕНЫ ПОТЕРЯН при разборе. Начало и конец равны (или конец
    # меньше) — станок выглядит не работавшим ни минуты, и всё его время висит
    # в отчёте «простой — причина не указана». Прогон 27.09.2026, ст.98: разбор
    # записал «21563900 → 21563900», хотя Симонова в том же сообщении написала
    # вечернее «Сч 21574050» -> 0 ч работы машины и «станок −5,83 ч».
    #
    # Число не выдумывается: берётся показание того же разряда из ЭТОЙ ЖЕ темы
    # станка, записанное правее начала смены, и только если выпуск им не
    # превышает физический предел станка. Если большего показания в теме нет —
    # станок стоял честно: прогон 15.09.2026, ст.321, где одно и то же число
    # написано трижды и нулевой выпуск верен.
    if start is not None and end is not None and float(end) <= float(start):
        matches = _counter_matches(text)
        digits = len(str(int(start)))
        last_start = max((i for i, m in enumerate(matches)
                          if int(m.group(1)) == int(start)), default=-1)
        limit = max_output(machine) or 0.0
        later = [int(m.group(1)) for i, m in enumerate(matches)
                 if i > last_start
                 and len(str(int(m.group(1)))) == digits
                 and int(m.group(1)) > int(end)
                 and (not limit or int(m.group(1)) - int(start) <= limit)]
        if later:
            candidate = max(later)
            notes.append(
                f"№{machine}: разбор записал конечное показание равным "
                f"начальному ({int(start)}) — станок выглядел не работавшим. "
                f"В этой же теме правее стоит {candidate}, выпуск считан от "
                f"него ({candidate - int(start)} узлов)." + _ASK_FIX)
            end = float(candidate)

    # 5. СЧЁТЧИК ЗА СМЕНУ ТОЛЬКО РАСТЁТ. Начало больше конца — одно из
    # показаний испорчено, и выпуск по такой паре в отчёт не идёт: прогон
    # 26.09.2026, ст.251 — «Общ сч 391938» утром вместо 301938 и «303370»
    # вечером дали «-88568» узлов в Excel, а станок выглядел простоявшим весь
    # день. Началом становится конечное за соседнюю смену — это НЕ выдуманное
    # число, а показание из журнала станка (тем же путём идёт перенос в
    # day_pipeline._carry_over_counters). Заменить нечем — убираем
    # начало: отчёт отдаёт «нет данных» вместо отрицательного выпуска.
    if start is not None and end is not None and start > end:
        limit = max_output(machine)
        if (prev_end is not None and prev_is_adjacent and prev_end <= end
                and (not limit or end - prev_end <= limit)):
            notes.append(
                f"№{machine}: начальное показание {int(start)} больше конечного "
                f"({int(end)}), а счётчик назад не отматывается — начало взято "
                f"с прошлой смены ({int(prev_end)})." + _ASK_FIX)
            start = float(prev_end)
        else:
            notes.append(
                f"№{machine}: начальное показание {int(start)} больше конечного "
                f"({int(end)}), а счётчик назад не отматывается. Какое из двух "
                f"чисел верное — неясно, выпуск и время по станку не "
                f"считаются." + _ASK_FIX)
            start = None

    # Начало смены ещё раз — теперь уже по ВЫПРАВЛЕННОМУ концу смены.
    boundary_now()

    return start, end, notes


def fix_machine_counters(machine: str,
                         lines: List[Dict],
                         text: str = "",
                         prev_end: Optional[float] = None,
                         prev_is_adjacent: bool = False,
                         operator: Optional[str] = None) -> List[str]:
    """Проверить все строки (ассортименты) станка на месте.

    Правит counter_start/counter_end в переданных словарях и возвращает
    заметки. Правятся только КРАЙНИЕ значения: промежуточные ассортименты
    остаются как их дала модель, иначе можно сломать верную разбивку.

    operator — фамилия оператора станка: по ней начало смены отделяется от
    утренней сводки мастера (см. check_counters, правило 0). Если её не
    передали, читаем из заголовка раздела «98 машина(Белякова)».
    """
    if not lines:
        return []
    starts = [ln.get("counter_start") for ln in lines
              if ln.get("counter_start") is not None]
    ends = [ln.get("counter_end") for ln in lines
            if ln.get("counter_end") is not None]
    if not starts and not ends:
        return []
    cur_start = min(starts) if starts else None
    cur_end = max(ends) if ends else None
    new_start, new_end, notes = check_counters(
        machine, cur_start, cur_end, text=text, prev_end=prev_end,
        prev_is_adjacent=prev_is_adjacent,
        operator=operator or section_operator(text))
    if not notes:
        return []
    for ln in lines:
        if starts and ln.get("counter_start") == min(starts):
            ln["counter_start"] = _as_int(new_start)
        if ends and ln.get("counter_end") == max(ends):
            ln["counter_end"] = _as_int(new_end)
    for n in notes:
        logger.warning("Проверка счётчика: %s", n)
    return notes
