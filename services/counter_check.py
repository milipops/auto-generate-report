# -*- coding: utf-8 -*-
"""Проверка показаний счётчика на опечатки мастера (прогон 14.09.2026).

Зачем это нужно. Счётчик — единственный источник времени работы станка:
часы = (конец - начало) / норма / 60. Одна опечатка в цифре ломает весь
отчёт, и выглядит это как катастрофа, а не как ошибка:

    прогон 14.09.2026, №321: мастер написал «Общ сч 1200807» вместо 120807
        -> дельта +1 080 054 узла -> «работа машины 3000,15 ч из 12 часов»
           и «!!! РАСХОЖДЕНИЕ: станок +2996,32 ч сверх 12 ч».
    прогон 14.09.2026, №151: мастер написал «Общ.сч. 7760351» вместо 760351
        -> дельта -6 994 283 -> работа 0 ч и «!!! РАСХОЖДЕНИЕ: станок -11,25 ч».

Модель здесь ни при чём: она честно передала то, что написано. И испорченное
число утекает в counter_ledger.json, отравляя перенос на следующую смену.

Сама проверка тоже способна накосячить — прогон 21.09.2026, №98: мастер
закрыла смену строкой «Общ. Счётчик 21509000», а шаблон умел читать только
«сч» + разделители + цифры и полное слово «Счётчик» не видел. Настоящее
конечное показание осталось не найденным, валидатор не нашёл его в
«правильных», объявил опечаткой и подставил последнее найденное:
21509000 → 21501650. Испорченное число уехало и в отчёт, и в
counter_ledger.json. Поэтому метку читаем вместе с окончанием слова, а
«доказательств не хватает» теперь значит «оставить как есть», а не
«подставить соседнее».

Как ловим — пятью независимыми признаками, ничего не выдумывая:

0. ГРАНИЦА СМЕНЫ. Начало смены — самое раннее показание, записанное в теме
   станка (передача смены вечером), а не первое показание оператора: сдвиг
   начала вперёд съедаёт наработку станка (27.09.2026, ст.111 — минус 159
   узлов). Вперёд начало отодвигается только если выпуск от раннего показания
   не влезает в смену (21.09.2026, ст.98 — 20,6 ч при смене 12 ч).

1. МОДАЛЬНАЯ ДЛИНА ЦИФР. За смену мастер пишет счётчик много раз (на каждом
   останове). У №151 за 14.09 было 13 значений: двенадцать шестизначных и
   одно семизначное. Семизначное — опечатка. Признак работает, потому что
   счётчик за смену растёт на сотни-тысячи узлов и разрядность не меняет.

2. ПРАВДОПОДОБИЕ ДЕЛЬТЫ. Выпуск за смену физически не может превысить
   12 ч x норму узлов/мин x 60. Для №321 (норма 6 узл/мин) это ~4320 узлов;
   дельта 1 080 054 больше в 250 раз.

3. СВЕРКА С ПРОШЛОЙ СМЕНОЙ (counter_ledger). Начальное показание должно быть
   близко к конечному за предыдущую смену того же станка: у №151 было
   754129 за 10.09, а «начало» 7760351 отличается на порядок.

4. КОНЕЦ СМЕНЫ НЕ ПОТЕРЯН при разборе. Начало равно концу (или конец меньше) —
   станок выглядел не работавшим ни минуты, хотя правее в той же теме стоит
   большее показание того же разряда. Прогон 27.09.2026, ст.98: разбор отдал
   «21563900 → 21563900», а вечернее «Сч 21574050» в сообщении оператора был.

5. ОДОМЕТР НЕ ИДЁТ НАЗАД. Начало больше конца — показаний такой пары в
   отчёте не будет: либо начало заменяется конечным за соседнюю смену (это
   запись журнала станка, а не догадка), либо выпуск остаётся «нет данных».
   Прогон 26.09.2026, ст.251: −88568 узлов дошли до Excel.

Числа НЕ подменяются молча: каждое исправление возвращается заметкой, и бот
показывает её словами. Если доказательств не хватает (показаний мало, нормы
нет) — данные остаются как есть: лучше честное расхождение, чем выдуманная
цифра.
"""
from __future__ import annotations

