@dataclass
class MachineRemains:
    """Блок «остатки и отходы» по одному станку за смену.

    Поля намеренно необязательные: мастер может прислать только отходы или,
    наоборот, только показания. Пустое поле остаётся None и в отчёте выглядит
    как «—» — это честнее нуля, потому что ноль значит «сдал ноль килограммов».
    """
    machine: Optional[str] = None
    operator: Optional[str] = None
    # «конец» / «начало» — что мастер пометил в заголовке блока.
    moment: str = ""
    # Показания: ключ → (факт, «из чего»). Второй элемент None, если «из» нет.
    counters: Dict[str, Tuple[Optional[float], Optional[float]]] = \
        field(default_factory=dict)
    # Отходы по видам, кг. Ключи из WASTE_KEYS.
    waste: Dict[str, Optional[float]] = field(default_factory=dict)
    # Причина «прочих» отходов — мастер обязан её указать.
    other_reason: str = ""
    # Состояние машины и полотна словами (недочёты, не закрытые к смене).
    state: str = ""
    # Индексы сообщений, из которых собран блок — чтобы можно было проверить.
    sources: List[int] = field(default_factory=list)
    # Килограммы, названные в сообщении, но без вида отходов («… 11,0 кг»).
    # В цифры не идут — про них говорим словами, решение за человеком.
    unknown_kg: List[str] = field(default_factory=list)

    def counter(self, key: str) -> Optional[float]:
        return (self.counters.get(key) or (None, None))[0]

    def counter_of(self, key: str) -> Optional[float]:
        """Значение «из ____» (план/задание) по показанию."""
        return (self.counters.get(key) or (None, None))[1]

    def counter_text(self, key: str) -> str:
        """«148 из 150» либо «148», либо «—» — как в сообщении мастера."""
        fact, of = self.counters.get(key) or (None, None)
        if fact is None and of is None:
            return "—"
        if of is None:
            return _num(fact)
        return f"{_num(fact)} из {_num(of)}"

    @property
    def waste_total(self) -> float:
        """Всего сдано отходов по станку, кг. Незаполненные виды — не ноль."""
        return round(sum(v for v in self.waste.values()
                         if isinstance(v, (int, float))), 3)

    @property
    def has_waste(self) -> bool:
        return any(isinstance(v, (int, float)) for v in self.waste.values())

    @property
    def has_counters(self) -> bool:
        return any(v[0] is not None for v in self.counters.values())

    @property
    def ok(self) -> bool:
        """Есть хоть что-то заполненное (иначе блок бессмысленный)."""
        return bool(self.has_waste or self.has_counters or self.state)

    @property
    def waste_kinds_text(self) -> str:
        """Отходы одной строкой: «навивка шпулей 3,5; наладочные 1 кг»."""
        parts = [f"{WASTE_LABELS[k].split(' (')[0].lower()} {_num(v)}"
                 for k, v in self.waste.items()
                 if isinstance(v, (int, float)) and v]
        return "; ".join(parts)


@dataclass
class DayRemains:
    """Остатки и отходы по всем станкам смены."""
    date: str = ""
    machines: List[MachineRemains] = field(default_factory=list)
    # Проблемы разбора, которые нужно сказать словами (решение — за человеком).
    warnings: List[str] = field(default_factory=list)

    @property
    def ok(self) -> bool:
        return any(m.ok for m in self.machines)

    def totals(self) -> Dict[str, float]:
        """Итого по видам отходов за смену, кг."""
        out: Dict[str, float] = {}
        for key in WASTE_KEYS:
            s = sum(m.waste.get(key) or 0.0 for m in self.machines
                    if isinstance(m.waste.get(key), (int, float)))
            out[key] = round(s, 3)
        return out

    @property
    def waste_total(self) -> float:
        return round(sum(self.totals().values()), 3)

    def by_machine(self, machine) -> Optional[MachineRemains]:
        key = machine_rates._norm_key(machine)
        for m in self.machines:
            if machine_rates._norm_key(m.machine) == key:
                return m
        return None


# ──────────────────────────────── разбор текста ────────────────────────────────

# Хвосты подписей показаний, после которых тире+число — это ЗНАЧЕНИЕ, а не
# заголовок раздела: «Общ.сч. - 100», «Ср.сч. - 251», «Подмена - 4 из 5».
_NOT_SECTION_TAIL = ("сч", "из", "навито", "развито", "срез", "подмен", "кг",
                     "узл", "шт", "расширен", "всего", "итого", "полотен")


def _matched_number(match) -> Optional[str]:
    """Номер из той группы регэкспа, которая реально совпала.

    В _MACHINE_RE номер раздела — это group(3), а в _SECTION_HEAD_RE —
    group(1); брать «просто group(1)» нельзя (прогон 10.09.2026: все
    заголовки «–N» отбраковывались пустым номером).
    """
    for i in range(1, (match.re.groups or 0) + 1):
        if match.group(i) is not None:
            return match.group(i)
    return None


def _is_section_head(text: str, match) -> bool:
    """Это заголовок раздела «–N», а не значение показания со знаком «-».

    Две защиты (прогон 10.09.2026):
      • номер обязан быть станком из справочника норм — «Общ.сч. - 100» не
        превращается в станок №100;
      • перед тире не должно быть хвоста подписи показания — иначе
        «Ср.сч. - 251» (значение, совпавшее с номером станка) откроет
        несуществующий раздел и отрежет настоящие показания.
    """
    key = machine_rates._norm_key(_matched_number(match))
    if key not in set(machine_rates.known_machines()):
        return False
    # Смотрим ТОЛЬКО текст, НЕПОСРЕДСТВЕННО примыкающий к тире (в пределах
    # текущей строки, без хвостовых пробелов):
    #   «Ср.сч. - 251»   → перед тире «Ср.сч.»  → это значение, не раздел;
    #   «…6 шт со стороны выхода полотна. –251» → перед тире «полотна.» →
    #     это заголовок раздела (прогон 10.09.2026: поиск по ВСЕЙ строке
    #     отбраковывал его из-за слова «шт» в середине предложения).
    line_start = (text or "").rfind("\n", 0, match.start()) + 1
    before = (text or "")[line_start:match.start()].rstrip().lower()
    return not any(before.endswith(w) for w in _NOT_SECTION_TAIL)


def _section_head_positions(text: str) -> List[Tuple[int, str]]:
    """[(позиция, станок)] заголовков разделов «–N» по порядку."""
    norm = normalize_text(text)
    return [(m.start(), machine_rates._norm_key(_matched_number(m)))
            for m in _SECTION_HEAD_RE.finditer(norm)
            if _is_section_head(norm, m)]


def normalize_text(text: str) -> str:
    """Привести текст к NFC и заменить неразрывные пробелы обычными.

    Причина (прогон 10.09.2026): из Яндекс Мессенджера/Telegram слова приходят
    в NFD — «Общий» как «Общи» + U+0306 (combining breve), то есть буква «й»
    разложена на две кодовые точки. Поиск маркера «общий сч» по такому тексту
    НЕ срабатывает, и конечное показание станка (278755 у №251) терялось
    целиком: отчёт считал станок недоработавшим, а остатки уезжали на №151.

    Нормализуем ДО поиска маркеров, чтобы все позиции считались по одному и
    тому же тексту. NFC выбран, а не NFD: маркеры в коде записаны в NFC.
    """
    if not text:
        return text or ""
    out = unicodedata.normalize("NFC", text)
    # Разметка мессенджера. Мастер выделяет жирным весь бланк, и из выгрузки
    # приезжает «**Общ.сч**. -223351». Маркер со звёздочками внутри не
    # узнаётся, и показания станции теряются целиком: прогон 25.09.2026 ст.111
    # (в «Остатках» по станции не было НИ ОДНОГО счётчика), 24.09 ст.111 и
    # 21.09 ст.151 (вместо конца смены печатали утренние числа).
    #
    # Подчёркивания НЕ трогаем: ими мастера заполняют пустые клетки бланка
    # («_3001____ из 2700____»), и «__» как признак полужирного здесь
    # неотличимы от пробелов бланка.
    out = re.sub(r"\*+", "", out)
    # Нерарывный/узкий пробел мастера вставляют вместо обычного — для
    # регулярок они «не пробел», поэтому приводим к единому виду.
    return (out.replace("\u00a0", " ").replace("\u2007", " ")
               .replace("\u202f", " ").replace("\u2009", " ")
               .replace("\u200b", ""))


def last_section_machine(text: str) -> Optional[str]:
    """Станок ПОСЛЕДНЕГО заголовка раздела «–N» в тексте.

    Нужен для переноса контекста между сообщениями: длинную переписку
    Telegram режет на части по 4096 знаков, и разрез попадает ПОСЕРЕДИНЕ
    обсуждения станка (прогон 10.09.2026: «–251» оказался в первом
    сообщении, а «Конец смены … Общий сч.: 278755» — во втором). Хвост без
    заголовка надо отнести к тому же станку, иначе блок уходит в «станок не
    указан», а показания теряются.
    """
    heads = _section_head_positions(text)
    return heads[-1][1] if heads else None


def _find_machine(line: str) -> Optional[str]:
    """Номер станка из строки, если он там назван и есть в справочнике норм."""
    known = set(machine_rates.known_machines())
    for m in _MACHINE_RE.finditer(line or ""):
        num = m.group(1) or m.group(2) or m.group(3)
        key = machine_rates._norm_key(num)
        if key in known:
            return key
    return None


def _match_marker(low: str, table) -> Optional[Tuple[str, int]]:
    """(ключ поля, где кончился маркер) для первой подошедшей строки таблицы."""
    for key, markers in table:
        for marker in markers:
            pos = low.find(marker)
            if pos >= 0:
                return key, pos + len(marker)
    return None


def _split_of(text: str) -> Tuple[Optional[float], Optional[float]]:
    """«148 из 150» → (148, 150). «148» → (148, None)."""
    # Сразу за подписью идут ЧАСЫ — мастер описывает расписание, а не пишет
    # строку бланка: «С 12:10 до 13:10 подмена 13:10 пуск машины»
    # (прогон 24.09.2026, ст.91). Показанием счётчика часы быть не могут —
    # тот же смысл, что и защита «из 516:38» ниже.
    if _TIME_VALUE_RE.match(text or "") or _CLOCK_RANGE_RE.match(text or ""):
        return None, None
    # Слева запрещена БУКВА, а не граница слова: мастер пишет «Подмена 2из 4»
    # (31.08.2026, ст.251) — после цифры «\b» не возникает, и план терялся,
    # а ближайший «из» брался из следующей строки бланка («303 из 303»).
    # Справа запрещена буква: иначе «из» внутри «измерение» резало бы значение.
    # Регистр не важен: выгрузка склеивает строки, и план приезжает с большой
    # буквы — «Ср. Сч 300 уз. Из 1450 Всего 8 срезов» (№98, 29.09.2026). Без
    # «И» планом становилась четвёрка из следующей фразы, и в отчёт уходило
    # «300 из 4» вместо «300 из 1450».
    parts = re.split(r"(?<![а-яёa-z])[иИ]з(?![а-яёa-z])", text or "", maxsplit=1)
    # Показания читает _to_counter, а не _to_number: в строке «Подмена 4 из 4
    # 212 протяжных узлов» план — 4, а «212» подписано своими словами.
    fact = _to_counter(parts[0])
    of = _to_counter(parts[1]) if len(parts) > 1 else None
    # Экспорт склеивает строки без пробелов: «Подмена 4 из 5\n16:38 пуск»
    # превращается в «из 516:38», и планом становилось число 516, которого
    # мастер не писал (прогон 10.09.2026, ст.251 и 321). Если сразу за «из»
    # идёт время «ЧЧ:ММ» — числа «из чего» тут нет.
    if of is not None and len(parts) > 1 \
            and re.match(r"\s*\d+\s*[:;.ч]\s*\d{1,2}(?!\d)", parts[1]):
        of = None
    return fact, of


def _other_reason(line: str, tail: str) -> str:
    """Причина «прочих» отходов из строки мастера.

    В пустом бланке в скобках стоит подсказка «(указать причины появления)» —
    это НЕ причина, иначе в отчёте у каждого станка была бы одна и та же
    бессмысленная строка.
    """
    reason = ""
    brackets = re.search(r"\(([^)]*)\)", line or "")
    if brackets:
        inner = brackets.group(1).strip()
        low = inner.lower()
        if inner and "указать" not in low and "причин" not in low:
            reason = inner
    if not reason:
        # Причину могли дописать после числа: «Прочие - 2кг, обрыв нити».
        # Скобки выбрасываем целиком: если в них была подсказка бланка, её
        # остаток («указать причины появления) - ____кг») иначе уезжает в отчёт.
        rest = re.sub(r"\([^)]*\)", " ", tail or "")
        rest = re.sub(r"^[^)]*\)", " ", rest)
        reason = re.sub(r"^[\s)(:–—-]*[\d\s.,]*(?:кг)?[\s.,:–—-]*", "",
                        rest).strip(" .,:–—-()")
        low = reason.lower()
        if "указать" in low or "причин" in low:
            reason = ""
    # Незаполненный бланк: остались только прочерки, цифры и «кг».
    if re.fullmatch(r"[\s_\-–—.,:0-9]*(?:кг)?[\s_\-–—.,:]*", reason or "",
                    flags=re.I):
        return ""
    if not reason or set(reason) <= set("_-–— .,"):
        return ""
    return reason


def _looks_like_waste(low: str) -> bool:
    """Строка про сдаваемые отходы: «кг» или явный вид отходов."""
    if "кг" in low:
        return True
    # Маркер сравниваем в нижнем регистре: «Развивка » в таблице написан с
    # заглавной только ради учёта регистра в _marker_positions, а здесь важна
    # сама фраза.
    return any(marker.lower() in low
               for _key, markers in _WASTE_MARKERS for marker in markers
               if marker not in ("прочие", "прочее", "прочих"))


# Разбор идёт ПО ПОЗИЦИЯМ МАРКЕРОВ В ТЕКСТЕ, а не по строкам. Причина: в
# сообщениях мастеров (прогон 08.09.2026) весь блок часто приходит одной
# строкой — «Конец смены: Общ.сч. -745636 Ср.сч. - 15051 из 14500 Срез - 1 из
# 1 …», а отходы вообще пишутся фразой посреди текста («Наладочных узлов после
# 1 подмены шпулей 12кг»). Построчный разбор в таком тексте видел только первый
# маркер строки и терял почти всё.

# Сколько символов текста вокруг считаем «рядом». Показания одного замера
# мастера идут подряд, поэтому разрыв больше этого — уже другой замер.
_NEAR = 220
# Сколько минимум РАЗНЫХ показаний должно стоять рядом, чтобы считать это
# замером, а не случайным словом («подмена» в переписке встречается постоянно).
_MIN_CLUSTER = 3

# Между числом и «кг» мастер может оставить подчёркивания пустого бланка
# («От навивки шпулей(шпульный стол) - 0,085___кг», ст.151 за 09.09.2026) —
# без [\s_\-–—]* число терялось, а срабатывала «пустая» альтернатива.
# Пробел после десятичного разделителя — артефакт выгрузки чата: «Вес отходов
# после подмены 10, 4кг» (ст.111 за 21.09.2026). Без [ \t\u00a0]* разбор читал
# число «4» и требовал для него вида отходов, хотя это те же самые 10,4 кг,
# подписанные строкой бланка в конце смены.
_KG_RE = re.compile(
    r"(\d[\d\s ]*(?:[.,][ \t\u00a0]*\d+)?)[\s_\-–—]*кг|([_\-–—]{2,})\s*кг",
    re.IGNORECASE)
# «Вес срезанных узлов -0,525» (ст.151 за 09.09.2026) — килограммы БЕЗ слова
# «кг», но с явного «веса». Правило пользователя (09.09.2026): такие
# килограммы сдаются и должны учитываться (как «Вес срезанных протяжных =
# 11,0 кг» на ст.251 за 08.09). Число не берём, если за ним идёт единица
# счёта («167 узлов», «151шт») — это не килограммы; «11,0 кг» ловит _KG_RE.
_WEIGHT_RE = re.compile(
    r"(?:\bвес|\bмасса)\w*[^.\n]{0,40}?[-–—=]?\s*"
    r"(\d[\d\s ]*(?:[.,]\d+)?)"
    # Цифра/десятичное продолжение ВПЛОТНУ к числу — значит число склеилось с
    # следующим («…узлов-0,5259:38» в экспорте без переносов): такое место
    # неоднозначно, килограммы из него не берём. Единицы счёта — тоже не кг.
    r"(?!\d|[.,]\d|\s*(?:уз|шт|шп\b|бабин|бобин|полот|яч|мин|:\d))",
    re.IGNORECASE)
# Ответ на инвентаризацию сырья — НЕ запись об отходах. Прогон 24.09.2026,
# ст.321: «Сырье для навивки шпуль … 16 шт из них 1 шт 2,6кг и 15шт от 3,8кг
# до 4,2 кг» дало в отчёте «отходы от навивки шпулей 4,2 кг», хотя слова
# «отходы» во всей теме №321 нет ни разу — мастер перечислял вес паковок.
# Прогон 22.09.2026, ст.151: «172 катушки малым весом(от 550-700)» дало 550 кг
# вместо настоящих «При подмене шпулярника пэ 1,2 - 5,2кг» в той же строке.
# Вес ЕДИНИЦЫ («бобины по 0,925кг», «1 шт 2,6кг», «катушек (весом ± 1,400 кг)»)
# и границы диапазона («от 3,8кг до 4,2 кг», «от 550-700») — не показание
# бланка: там всегда «вид отходов - N кг» или «= N кг».
# «Весом ± N кг» — это паспортный вес одной катушки из инструкции мастера
# (прогон 26.09.2026, ст.321: «подготовка катушек (весом ± 1,400 кг)»), а не
# сданные отходы. Строка бланка так не пишется: там перед числом слово ВИДА.
_PER_UNIT_WEIGHT_RE = re.compile(
    r"(?:\bпо|\bшт\.?|\bвесом\s*[±+\-–—]?)\s*$", re.IGNORECASE)
# Вес назван ПРИМЕРНО — его не взвешивали на весах, и сдачей за смену он не
# считается: «отходы после замены шпулярника с ориентировочным весом 4,5 кг»
# (24.09.2026, ст.151) и «бобинами ориентировочным весом 1,11кг это чистый
# вес» (ст.321). Мастер про такой вес только предупреждает, вид отходов к нему
# не подписывает — требовать его бессмысленно.
_APPROX_WEIGHT_RE = re.compile(r"(?:ориентировочн|примерн|приблизит)\D{0,24}$",
                               re.IGNORECASE)
# Число из ПРИМЕРА — так руководитель показывает, как подписывать запись, и к
# сдаче за смену оно отношения не имеет. Прогон 26.09.2026, ст.251: «произвести
# запись например ( шпиндель 3, шпули с 20 по 25 , вес 0.12 кг)» — разбор
# требовал назвать вид отходов к 0.12 кг, хотя никто эти килограммы не взвешивал
# и не сдавал. Между «например» и числом не должно быть закрывающей скобки:
# дальше пример кончился, и обычный вопрос про вид отходов остаётся вопросом.
_EXAMPLE_RE = re.compile(r"например[^)]{0,160}$", re.IGNORECASE)
# Килограммы в скобках САМИ ПО СЕБЕ — это ответ на вопрос руководителя про
# размер сырья, а не запись о сдаче. Прогон 26.09.2026, ст.321: «Мне сказали
# большие снимать на их место маленькие (1,400 кг) Тогда с поддона брать?» —
# разбор просил назвать вид отходов к 1,400 кг, хотя ни один килограмм в тот
# час никто не взвешивал и не сдавал; мастер выбирает бобину со шпулярника.
# Строка бланка так не пишется: перед числом там стоит название вида отходов,
# поэтому правило только СНИМАЕТ вопрос, но не мешает записи, если вид всё же
# назван («Наладочные (10,4кг)» по-прежнему считается наладочным отходом).
_PAREN_WEIGHT_RE = re.compile(r"[(«[]\s*\d[\d., ]*\s*(?:кг|гр|г)\s*[)»\]]",
                              re.IGNORECASE)
_WEIGHT_RANGE_RE = re.compile(
    r"от\s*\d[\d., ]*\s*(?:кг|гр|г)?\s*(?:до|[-–—])\s*\d[\d., ]*\s*"
    r"(?:кг|гр|г)?"
    # Тот же перечень, только без «от»: «Вес вместе со втулкой 1,405кг-1,410кг»
    # (24.09.2026, ст.321). Строка бланка так не пишется — перед прочерком там
    # всегда слово вида отходов («Наладочные - 4кг»), а не число с единицей;
    # «3,5(красный)-4,6 кг» (16.09) тоже мимо: после 3,5 стоит скобка.
    # Заголовки станков в выгрузке начинаются с тире («–251 машина»), поэтому
    # единица измерения обязательна с ОБОИХ сторон числа, а перенос строки
    # внутри диапазона запрещён: иначе «3,2 кг ⏎ –251 машина» (14.09) сошло бы
    # за диапазон и съело настоящую протяжку узлов.
    r"|\d[\d.,]*[ \t]*(?:кг|гр|г)[ \t]*(?:до|[-–—])[ \t]*\d[\d.,]*[ \t]*(?:кг|гр|г)",
    re.IGNORECASE)
# Брак сырья, отправленный на экспертизу, — НЕ сдача отходов смены. Прогон
# 25.09.2026, ст.251: «На шпулярнике заменены 3 бобины имеющие внешневидовой
# порок (штопор, выбивание одной стренги) общий вес 6,1 кг, бобины будут
# переданы в лабораторию». Разбор требовал назвать вид отходов к 6,1 кг, хотя
# нитка уехала не в отходы, а на проверку поставщику. В строке бланка
# («Наладочные - 4кг») лаборатории стоять не может, поэтому ищем слово вокруг
# числа, а не по всему сообщению.
_LAB_RE = re.compile(r"лаборатори\w*", re.IGNORECASE)
# Сколько символов вокруг числа — то же предложение про брак (см. _NEAR).
_LAB_NEAR = 200
# «3 ср. из 4 ср.» (ст.98), «1 срез из 2х» (24.09.2026, ст.91) и «1 Ср из 4»
# (14.09.2026, ст.98) — срез, записанный ЧИСЛОМ ПЕРЕД подписью. Отдельным
# правилом, потому что маркер «срез» требует цифру ПОСЛЕ себя.
# Хвост «ср» после плана был обязателен, пока встречалась только краткая форма
# («3 ср. из 4 ср.»); теперь он не нужен: «из» обязано стоять сразу за подписью,
# и потому «Ср 1350 из 1650» (число ПОСЛЕ подписи) сюда не попадает.
_SREZ_SHORT_RE = re.compile(r"(\d+)\s*(?:срез|ср\.?)\s*из\s*[.:_\-–—=]*\s*(\d+)",
                            re.IGNORECASE)
# Число с единицей «уз» внутри окна — это УЗЛЫ, то есть счётчик, а не количество
# операций. Так мастер подписывает срезовой (средний) счётчик одним словом
# «срез»: «Срез 950 уз. из 1600 уз.» (24.09.2026, ст.91) и «Срез. 1000 ⏎ Сч из
# 1450 уз» (22.09.2026, ст.98) легли в колонку «срезы», хотя срезов там никто не
# считал. Требует цифру сразу перед «уз», поэтому «Срез 3 из 3» не касается.
_COUNTER_UNITS_RE = re.compile(r"\d[\d.,]*\s*уз", re.IGNORECASE)
# После подписи показания ОБЯЗАНО идти число (или прочерки пустого бланка).
# Прогон 10.09.2026: в таймлайне мастера слова «подмена» и «срез» встречаются
# как названия операций, и «10.05-10.55 подмена Навивка шпулей 250 из 250»
# читалось как показание «Подмена 250 из 250» (вместо настоящих «4 из 1»),
# а «Подмена произведена не полностью, без 18 шпулей» давало «Подмена 18».
_VALUE_START_RE = re.compile(r"^[\s.:_\-–—=]*(?:\d|[_\-–—]{2,})")
# ЧАСЫ вместо показания: «подмена 13:10 пуск машины» (24.09.2026, ст.91) —
# мастер описывает расписание простоя, а не пишет строку бланка. Тот же смысл,
# что и защита «из 516:38» в _split_of. Точку разделителем часов не берём:
# «14.3» — обычная дробь, а «9.20» в переписке стоит после предлога, не после
# подписи показания.
_TIME_VALUE_RE = re.compile(r"[\s.:_\-–—=]*\d{1,2}\s*:\s*\d{2}(?!\d)")
# …и ЧАСЫ, записанные через точку: «Подмена 9.45-10.35», «Подмена 16.00-16.55»
# (прогон 14.09.2026, ст.98). Мастер описывает окно простоя, а в «Остатках»,
# Excel и выгрузке 1С стояло показание счётчика «подмена 16». Показание узлов
# целое, а здесь дробь ровно с ДВУМЯ цифрами после точки с обоих сторон тире и
# в правдоподобных границах часов (минуты < 60) — это время, а не число.
# Одиночную дробь паттерн не трогает: «1.5-2» не совпадает (после точки две
# цифры с обеих сторон), «11,45» и «14,5» — через запятую.
_CLOCK_RANGE_RE = re.compile(
    r"[\s.:_\-–—=]*(?:[01]?\d|2[0-3])[.][0-5]\d\s*[–—-]\s*"
    r"(?:[01]?\d|2[0-3])[.][0-5]\d(?!\d)")
# Маркер вида отходов считается настоящим, только если рядом килограммы или
# это строка бланка «от …». Иначе «Шпульный стол в работе» (ст.251, 10.09)
# становился барьером и отрезал показание «Шпуля: навито — 287 из 303».
_WASTE_PREFIX_RE = re.compile(r"(?:^|[\s(\[.:,;–—-])от\s*$", re.IGNORECASE)


def _marker_positions(text: str, table) -> List[Tuple[int, int, str]]:
    """Все вхождения маркеров таблицы: [(начало, конец, ключ), …] по порядку.

    Маркер, записанный в таблице С ЗАГЛАВНОЙ буквы, ищется с учётом регистра —
    так задают слова, которые мастер пишет только в начале отчётного
    предложения (см. комментарий к «Развивка » в _WASTE_MARKERS). Остальные
    читаются без регистра, как и раньше.
    """
    norm = unicodedata.normalize("NFC", text or "")
    low = norm.lower()
    out: List[Tuple[int, int, str]] = []
    for key, markers in table:
        for marker in markers:
            hay = norm if marker[:1].isupper() else low
            start = 0
            while True:
                pos = hay.find(marker, start)
                if pos < 0:
                    break
                out.append((pos, pos + len(marker), key))
                start = pos + 1
    out.sort()
    return out


def _machine_at(positions: List[Tuple[int, str]], pos: int,
                hint: Optional[str]) -> Optional[str]:
    """Станок для места в тексте: ближайший НАЗВАННЫЙ до него, иначе подсказка.

    В одном сообщении мастер может упомянуть чужой станок («культура
    производства около 121 м. 151м в работе»), поэтому берём последний
    названный ПЕРЕД цифрами, а не первый в сообщении.
    """
    found = None
    for at, num in positions:
        if at <= pos:
            found = num
        else:
            break
    return found or hint


def _machine_in(positions: List[Tuple[int, str]], start: int, end: int
                ) -> Optional[str]:
    """Станок, названный ВНУТРИ куска текста. Пусто, если не назван.

    Номер мастер пишет и после заголовка («Конец смены машина 321:»), поэтому
    сначала смотрим внутрь замера, а уже потом — что называлось раньше.
    """
    for at, num in positions:
        if start <= at < end:
            return num
    return None


def _own_machine(positions: List[Tuple[int, str]],
                 head: Optional[str], start: int, end: int,
                 hint: Optional[str]) -> Optional[str]:
    """Чей кусок текста, если по теме станок известен ТОЧНО.

    Порядок: номер внутри замера → шапка раздела «–N» → подсказка темы →
    последнее упоминание до замера. Подсказка темы стоит ВЫШЕ упоминания,
    потому что упоминание — это слова мастера про чужую машину, а не подпись
    показания (прогон 26.09.2026, ст.251: «помощь Петровского О на 151м»
    написана в 16:16, а вечерний замер 251-й — в 19:00; прежнее «последнее
    упоминание до цифр» отдавало весь конец смены несуществующей в выгрузке
    151-й, и туда же уезжала строка «Состояние машины»).
    """
    return (_machine_in(positions, start, end)
            or head
            or hint
            or _machine_at(positions, start, None))


# Терпимые маркеры показаний: PDF, напечатанный из мессенджера/браузера,
# отдаёт «й» как удвоенную «и», а layout-режим вставляет лишние пробелы
# (реальный прогон 10.09.2026: «* Общии   сч.: 278755»). Буквальный поиск
# «общий сч» такое не находит, и КОНЕЧНОЕ показание станка терялось.
# Регулярки идут ДОПОЛНЕНИЕМ к _COUNTER_MARKERS: позиция берётся по началу
# совпадения, конец — там же, где у буквального маркера.
_COUNTER_MARKERS_RE: List[Tuple[str, "re.Pattern"]] = [
    # Точка после сокращения и НЕОБЯЗАТЕЛЬНЫЕ «и/ы» — как у среднего счётчика
    # ниже: мастер подписывает итог «Общ. Счётчик 21509000» (21.09.2026, ст.98).
    # Без этой формы буквальная «общ. сч» оставляла хвост «ётчик 21509000»,
    # который значением не считался, и конечное показание терялось совсем.
    ("общий_счётчик", re.compile(
        r"(?:общ|об)\.?\s*(?:[иы]{1,3})?[йе]?\.?\s*"
        r"(?:сч[её]тчик|сч[её]т|сч)",
        re.IGNORECASE)),
    # Окончание слова («чик») входит в маркер: после «Срезовой счет» остаётся
    # хвост «чик -4720», и значение не находится. Так же «общий счетчик» —
    # прогон 31.08.2026, ст.251: без этого средний счётчик («4720 из 15900»)
    # не читался вообще, а «из 15900» уезжало планом в общий счётчик.
    # «и/ы» перед «й» теперь НЕ обязательны: «-овой» заканчивается на «й», и
    # старый класс [иы]{1,3} на «срезовой» спотыкался.
    ("средний_счётчик", re.compile(
        r"(?:ср|средн|срезов)\s*[а-яё]{0,3}\s*(?:[иы]{1,3})?[йе]?\s*"
        r"(?:сч[её]тчик|сч[её]т|сч)", re.IGNORECASE)),
]

# Показания БЕЗ уточняющего слова. Выгрузка 22.09.2026, ст.98: «Склад
# 49-24.08.26 187.3 51 250.5 зел Сч 21509000» — мастер пишет «Сч» и без
# «Общ.», из-за чего конечное показание не попадало ни в «Остатки», ни в расчёт
# времени по счётчику.
#
# Берём только ОТДЕЛЬНОЕ «Сч»/«Сч.»/«счёт»: «расчёт» отсекается границей слова
# (перед «сч» стоит буква), а «Ср.сч» и «Общ. сч» отсекает _counter_positions —
# там «сч» лежит ВНУТРИ уже найденной подписи, и подменило бы общий счётчик
# средним.
_BARE_COUNTER_MARKERS_RE: List[Tuple[str, "re.Pattern"]] = [
    ("общий_счётчик", re.compile(r"(?<![\w])сч(?:ет|ёт)?(?![\w])",
                                 re.IGNORECASE)),
]
# …и не стоит сразу за словом, которое уточняет ДРУГОЙ показатель: «Ср.  сч»
# (с двумя пробелами) не находится ни одним буквальным маркером, и голое «сч»
# утянуло бы 15070 в общий счётчик. Список именно про «какой счётчик», а не
# про «начало/конец смены» — там «Сч 21509000» и есть общий счётчик.
_BARE_AFTER_QUALIFIER_RE = re.compile(
    r"(?:общ|об|ср|средн|срезов|прош|пред)[а-яё]*[\s.:,_\-–—=]*$",
    re.IGNORECASE)
# …и не значение вида «1000 из 1450». Общий одометр мастер пишет ОДНИМ числом
# («Сч 21509000»), дробь «сколько из скольки» — это частичный счётчик со своим
# ярлыком. Выгрузка 21.09.2026, ст.98: «Со.сч.1000 из 1450» — опечатка в ярлыке
# («Со» вместо «Ср»), из-за которой общим счётчиком вставали 1000 из 1450, а
# настоящий итог 21509000 терялся.
# Между числом и «из» разрешены только цифры и пробелы: «Сч 21509000 Ср.сч 500
# из 1450» — это общий одометр и следующая подпись, а не дробь одного показания.
_BARE_FRACTION_VALUE_RE = re.compile(
    r"[\s.:,_\-–—=]*\d[\d ]*из(?![а-яёa-z])", re.IGNORECASE)


def _counter_marker_regex_positions(text: str) -> List[Tuple[int, int, str]]:
    """То же, что _marker_positions, но по терпимым регуляркам."""
    out: List[Tuple[int, int, str]] = []
    for key, pattern in _COUNTER_MARKERS_RE:
        for m in pattern.finditer(text or ""):
            out.append((m.start(), m.end(), key))
    out.sort()
    return out


def _bare_counter_marker_positions(text: str) -> List[Tuple[int, int, str]]:
    """Показания без уточняющего слова («Сч 21509000»).

    Отбрасывает «сч» после слова, которое называет ДРУГОЙ показатель («Ср.  сч»
    с двумя пробелами не читается ни одним маркером, а значение у него
    среднее), и «сч» с дробным значением («1000 из 1450») — у общего одометра
    плана «из скольки» не бывает.
    """
    src = text or ""
    out: List[Tuple[int, int, str]] = []
    for key, pattern in _BARE_COUNTER_MARKERS_RE:
        for m in pattern.finditer(src):
            if _BARE_AFTER_QUALIFIER_RE.search(src[:m.start()]):
                continue
            if _BARE_FRACTION_VALUE_RE.match(src[m.end():m.end() + 24] or ""):
                continue
            out.append((m.start(), m.end(), key))
    out.sort()
    return out


def _counter_positions(text: str) -> List[Tuple[int, int, str]]:
    """Показания, после которых действительно стоит число.

    Отсекает слова «подмена», «срез», «навито» из таймлайна операций: у
    настоящего замера сразу за подписью идёт цифра или прочерки бланка
    («Подмена - _2_ из _4_»), у упоминания операции — буква
    («подмена Навивка шпулей», «Подмена произведена не полностью»).
    """
    named = (_marker_positions(text, _COUNTER_MARKERS)
             + _counter_marker_regex_positions(text))
    # Отдельное «Сч» засчитывается общим счётчиком, только если это НЕ хвост
    # уже найденной подписи: в «Общ.сч» и «Ср.сч» те же буквы отвечают за
    # другой показатель, и голое «сч» приписало бы среднему значению общий
    # счётчик (или наоборот — перетёрло бы его).
    spans = [(at, fin) for at, fin, _key in named]
    candidates = list(named)
    for at, fin, key in _bare_counter_marker_positions(text):
        if any(first <= at < last for first, last in spans):
            continue
        candidates.append((at, fin, key))

    out: List[Tuple[int, int, str]] = []
    seen: set = set()
    for at, fin, key in sorted(candidates):
        # Один и тот же маркер может найтись и буквально, и регуляркой —
        # берём первое вхождение по позиции, чтобы не задвоить показание.
        # «Первое» — первое ПОДТВЕРЖДЁННОЕ: короткая подпись «общий счёт» —
        # начало слова «общий счётчик», и после неё остаётся хвост «чик
        # 1692500», который значением не считается (24.09.2026, ст.91 — так
        # терялось конечное показание общего счётчика). Значит, блокировать
        # этой позицией нельзя: иначе более длинная форма того же маркера
        # уже не проверяется.
        slot = (at, key)
        if slot in seen:
            continue
        if _VALUE_START_RE.match((text or "")[fin:fin + 12] or ""):
            seen.add(slot)
            out.append((at, fin, key))
    out.sort()
    return out


def _waste_positions(text: str) -> List[Tuple[int, int, str]]:
    """Маркеры видов отходов, похожие на ЗАПИСЬ об отходах.

    Настоящая запись: строка бланка («От навивки шпулей(шпульный стол) - 3,5кг»)
    или фраза с килограммами рядом («от разаивки 15 штук шпулей = 2 кг»).
    Простое упоминание («Шпульный стол в работе», «мониторинг навивки шпулей»)
    барьером и привязкой килограммов быть не должно.

    Килограммы «принадлежат» тому маркеру, который стоит к ним БЛИЖЕ ВСЕХ
    СПЕРЕДИ (та же логика, что в _read_waste). Брать «любой кг в пределах
    _NEAR» нельзя: в прогоне 10.09.2026 упоминание «Шпульный стол в работе»
    притянуло килограммы из фразы «от разаивки … = 2 кг» в конце сообщения,
    стало барьером и отрезало показание «Шпуля: навито — 287 из 303».
    """
    text = text or ""
    marks = _marker_positions(text, _WASTE_MARKERS)
    out: List[Tuple[int, int, str]] = []
    owned: set = set()
    for m in _KG_RE.finditer(text):
        owner = None
        for i, (at, fin, _key) in enumerate(marks):
            if fin <= m.start() and m.start() - fin <= _NEAR:
                owner = i
        if owner is not None:
            owned.add(owner)
    for i, (at, fin, key) in enumerate(marks):
        blank = re.match(r"[\s.:_\-–—=]*(?:\d|[_\-–—]{2,}\s*кг)",
                         text[fin:fin + 14] or "")
        if i in owned or blank or _WASTE_PREFIX_RE.match(text[:at] or ""):
            out.append((at, fin, key))
    return out


def _machine_positions(text: str) -> List[Tuple[int, str]]:
    known = set(machine_rates.known_machines())
    out: List[Tuple[int, str]] = []
    for m in _MACHINE_RE.finditer(text or ""):
        num = m.group(1) or m.group(2) or m.group(3)
        key = machine_rates._norm_key(num)
        if key not in known:
            continue
        if m.group(3) is not None and not _is_section_head(text or "", m):
            continue        # это значение показания, а не заголовок раздела
        # Позиция — начало САМОГО номера (m.start(i) = -1 у непрошедших
        # групп, поэтому выбираем по group(i), а не по start(i)).
        at = next(m.start(i) for i in (1, 2, 3) if m.group(i) is not None)
        out.append((at, key))
    return out


def _counter_regions(text: str, counters: List[Tuple[int, int, str]],
                     barriers: List[int]) -> List[Tuple[int, int, str]]:
    """Куски текста, где мастер выписал замер: [(начало, конец, момент), …].

    Замером считаем либо всё после заголовка «Конец(начало) смены», либо
    несколько разных показаний, стоящих рядом. Одинокое слово «подмена» в
    переписке замером не становится — иначе в отчёт полезли бы случайные числа.
    """
    heads = [(m.start(), m.group(1).lower())
             for m in _HEAD_RE.finditer(text or "")]
    stops = sorted(set(barriers + [m.start() for m in _HEAD_RE.finditer(text or "")]))
    regions: List[Tuple[int, int, str]] = []

    def _next_stop(after: int) -> int:
        for stop in stops:
            if stop > after:
                return stop
        return len(text or "")

    for at, moment in heads:
        regions.append((at, _next_stop(at), moment))

    # Скопления показаний без заголовка (мастер часто пишет замер просто так).
    group: List[Tuple[int, int, str]] = []

    def _flush(group):
        if len({k for _s, _e, k in group}) < _MIN_CLUSTER:
            return
        # Конец — ПОСЛЕ последнего маркера: там стоит его значение, иначе
        # последнее показание замера («Развито - 152 из 180») терялось.
        start, end = group[0][0], min(_next_stop(group[-1][1]),
                                      group[-1][1] + _NEAR)
        if any(start <= at < end for at, _m in heads):
            return   # уже покрыто заголовком
        # Границу не считаем перекрытием: мастер пишет «19:00 конец смены»
        # ПОСЛЕ показаний (ст.98 за 08.09), и такой замер терять нельзя.
        moment = ""
        for at, mom in heads:
            if abs(at - start) <= _NEAR or abs(at - end) <= _NEAR:
                moment = mom
                break
        cut = next((stop for stop in stops if start < stop < end), None)
        regions.append((start, cut if cut is not None else end, moment))

    for item in counters:
        if group and (item[0] - group[-1][1] > _NEAR
                      or any(group[-1][1] <= b <= item[0] for b in barriers)):
            _flush(group)
            group = []
        group.append(item)
    if group:
        _flush(group)
    regions.sort()
    return regions


def _read_counters(text: str, start: int, end: int,
                   counters: List[Tuple[int, int, str]],
                   barriers: List[int]) -> Dict[str, Tuple]:
    """Показания внутри одного замера. Первое ПОЛНОЕ значение по ключу.

    Два уточнения прогона 09.09.2026:
      • маркер, за которым сразу идёт буква, — часть ДРУГОГО слова: «срез»
        внутри «срезовой 750 из 750» и «срезанных узлов» давал ложные
        показания счётчика срезов;
      • если первое вхождение подписи значения не дало («Довязан 3 срез из 3»
        → fact=None), его заменяет следующее полное («Срез - 3 из 3» → 3 из 3).
        Первое значение по-прежнему главнее ВТОРОГО ПОЛНОГО: повтор подписи
        в отходах («после подмены на машине») замер не переопределяет.
    """
    inside = [c for c in counters if start <= c[0] < end]
    out: Dict[str, Tuple] = {}
    for i, (at, fin, key) in enumerate(inside):
        if re.match(r"[а-яёa-z]", text[fin:fin + 1], re.IGNORECASE):
            continue    # маркер — часть более длинного слова
        stop = inside[i + 1][0] if i + 1 < len(inside) else end
        for b in barriers:
            if fin <= b < stop:
                stop = b
                break
        value = _split_of(text[fin:stop])
        if key == "срез" and value != (None, None) \
                and _COUNTER_UNITS_RE.search(text[fin:stop] or ""):
            # «Срез 950 уз. из 1600 уз.» — это срезовой счётчик в узлах, а не
            # число срезов (см. _COUNTER_UNITS_RE).
            key = "средний_счётчик"
        prev = out.get(key)
        if prev is None:
            out[key] = value
            continue
        # Мастер пишет замеры по порядку, и «Конец смены» всегда ПОСЛЕ
        # промежуточных показаний. Прогон 10.09.2026, ст.98: «Ср сч 1260»
        # (08:30) и «Ср.сч 250узл. из 1400» (конец смены) попали в один
        # регион, и первое значение (1260) вытесняло итоговое.
        # Правило: более ПОЛНОЕ значение (есть план «из …») главнее; при
        # равной полноте — последнее, как и между регионами (последнее слово
        # за мастером).
        prev_full = prev[0] is not None and prev[1] is not None
        cur_full = value[0] is not None and value[1] is not None
        if value[0] is None and prev[0] is not None:
            continue            # пустая подпись бланка не затирает число
        if key == "общий_счётчик":
            # Для накопительного одометра «полнота» не довод: план «из скольки»
            # бывает у него ТОЛЬКО когда в окно маркера попала чужая подпись.
            # 21.09.2026, ст.98: «Общий сч.21486750 Со.сч.1000 из 1450» — утреннее
            # число с чужим планом оказывалось «полнее» итогового 21509000 и
            # вытесняло его; так же 24.08.2026, ст.251 («243884 из 15900» вместо
            # вечернего 245915). Значит, тут работает только хронология:
            # последнее слово за мастером.
            out[key] = value
            continue
        if cur_full or not prev_full:
            out[key] = value
    # Краткую форму берём ПОСЛЕДНЮЮ в регионе, а не первую: мастер пишет замеры
    # по порядку, и итог смены стоит в конце. Прогон 15.09.2026, ст.98: приёмка
    # «1 Ср из 4» (06:57) и конец смены «2ср. из 4 ср» (19:00) — за мастером
    # вторая. То же правило, что и для обычных маркеров выше.
    short = None
    for cand in _SREZ_SHORT_RE.finditer(text[start:end] or ""):
        short = cand
    if short and out.get("срез", (None, None))[0] is None:
        out["срез"] = (_to_number(short.group(1)), _to_number(short.group(2)))
    return {k: v for k, v in out.items()
            if v[0] is not None or v[1] is not None}


def _kg_matches(text: str) -> List[Tuple[int, "re.Match", bool]]:
    """Все килограммы по порядку: [(позиция числа, match, слово «кг» было)].

    Кроме явного «N кг» (_KG_RE) берём «Вес срезанных узлов -0,525» (_WEIGHT_RE,
    правило пользователя 09.09.2026) — то же самое «Вес срезанных протяжных
    (167 узлов) = 11,0 кг» со ст.251 за 08.09, только мастер не дописал «кг».
    Один и тот же кусок не берём дважды: «… = 11,0 кг» попадает в оба паттерна.
    Вес единицы сырья и границы диапазона отсекает _is_stock_weight (см.
    инвентаризацию сырья 24.09.2026).
    """
    ranges = [(m.start(), m.end())
              for m in _WEIGHT_RANGE_RE.finditer(text or "")]
    raw = [(m.start(1) if m.group(1) else m.start(), m, True)
           for m in _KG_RE.finditer(text or "")]
    raw += [(m.start(1), m, False) for m in _WEIGHT_RE.finditer(text or "")]
    raw.sort(key=lambda x: x[0])
    out: List[Tuple[int, "re.Match", bool]] = []
    for at, m, with_kg in raw:
        if out and out[-1][1].start() <= at < out[-1][1].end():
            continue          # тот же самый кусок текста, уже учтён
        if _is_stock_weight(text, at, ranges):
            continue
        out.append((at, m, with_kg))
    return out


def _is_stock_weight(text: str, at: int,
                     ranges: List[Tuple[int, int]]) -> bool:
    """Число — вес единицы сырья или граница диапазона, а не записанные отходы.

    ranges — вхождения «от A … до/– B» (_WEIGHT_RANGE_RE), посчитанные сразу
    для всего текста: у границы нет своей позиции без всего диапазона.
    """
    if _PER_UNIT_WEIGHT_RE.search((text or "")[:at]):
        return True
    return any(first <= at < last for first, last in ranges)


def _is_lab_transfer(text: str, at: int) -> bool:
    """Число — вес забракованных бобин, переданных в лабораторию, а не отходы.

    at — позиция числа в тексте. См. комментарий у `_LAB_RE`.
    """
    text = text or ""
    return bool(_LAB_RE.search(text[max(0, at - _LAB_NEAR):at + _LAB_NEAR]))


def _is_described_weight(text: str, at: int) -> bool:
    """Число описывает НЕ сдачу: пример, как подписывать запись, или размер бобины.

    Прогон 26.09.2026, ст.251: «3 произвести запись например ( шпиндель 3,
    шпули с 20 по 25 , вес 0.12 кг)» — руководитель показывает формулировку
    журнала. Так же ст.321: «Мне сказали большие снимать на их место маленькие
    (1,400 кг)» — мастер отвечает на вопрос про сырьё. Ни те, ни другие
    килограммы не взвешивали и не сдавали, поэтому требовать к ним вид отходов
    не у кого. at — позиция числа в тексте.
    """
    text = text or ""
    if _EXAMPLE_RE.search(text[:at]):
        return True
    return any(m.start() <= at < m.end()
               for m in _PAREN_WEIGHT_RE.finditer(text))


def _read_waste(text: str, wastes: List[Tuple[int, int, str]],
                machines: List[Tuple[int, str]], hint: Optional[str]
                ) -> Tuple[Dict[str, Dict[str, Optional[float]]], List[str]]:
    """Килограммы отходов: {станок: {вид: кг}} + непонятные «N кг».

    Ищем в тексте каждое «N кг» (и «вес … N» без слова «кг») и относим к
    БЛИЖАЙШЕМУ виду отходов перед числом. Так читается и строгий бланк
    («Наладочные - 4кг»), и живая фраза («Наладочных узлов после 1 подмены
    шпулей 12кг» → наладочные 12, а не 1), и «Вес срезанных узлов -0,525»
    (ст.151 за 09.09.2026 → протяжка узлов 0,525). Вид ищем по позиции ЧИСЛА,
    а не начала совпадения: в «Вес срезанных узлов -0,525» маркер вида
    («вес срезанных») стоит ВНУТРИ совпадения.
    """
    per_machine: Dict[str, Dict[str, Optional[float]]] = {}
    # Позиция последнего числа по (станок, вид): нужна, чтобы отличить вторую
    # сдачу в той же строке от переписанного веса в строке следующей.
    prev_at: Dict[Tuple[str, str], int] = {}
    reasons: Dict[str, str] = {}
    unknown: List[str] = []
    heads = _section_head_positions(text or "")
    for num_at, m, with_kg in _kg_matches(text or ""):
        # Просить «назовите вид отходов» бессмысленно, если вес назван ПРИМЕРНО
        # (его не взвешивали), это брак, уехавший на экспертизу, число из
        # ПРИМЕРА записи или паспортный вес бобины в скобках. Прогон
        # 26.09.2026, ст.321: «бобинами ориентировочным весом 1,11кг это чистый
        # вес» — мастер предупреждает о весе ОДНОЙ бобины, сдачей за смену такой
        # вес не бывает и подписывать вид отходов под него некому. Так же
        # «общий вес 6,1 кг, бобины будут переданы в лабораторию» (ст.251 за
        # 25.09) — нитка сдана не в отходы, а поставщику на проверку.
        not_a_handover = bool(_APPROX_WEIGHT_RE.search((text or "")[:num_at])) \
            or _is_lab_transfer(text, num_at) \
            or _is_described_weight(text, num_at)
        kind = None
        for at, fin, key in wastes:
            if fin <= num_at and num_at - fin <= _NEAR:
                kind = (at, fin, key)
        if kind is None and not with_kg:
            # «вес …» сам по себе маркер вида; ищем вид ПО ВНУТРИ совпадения.
            for at, fin, key in wastes:
                if m.start() <= at < m.end() or m.start() <= fin <= m.end() \
                        or (at < m.start() and fin > m.start()):
                    kind = (at, fin, key)
        if kind is None:
            # Вид не назван — просим его назвать, но не про примерный вес и не
            # про лабораторный брак (см. not_a_handover выше).
            if with_kg and m.group(1) and not not_a_handover:
                unknown.append(f"{m.group(1).strip()} кг")
            continue
        # «Весом N кг» отсекается раньше — в _kg_matches/_is_stock_weight:
        # это паспортный вес одной бобины, он не доходит даже до сюда. Здесь
        # отменять запись было бы нельзя: так же отсекались и настоящие сдачи
        # («Наладочные примерно 4кг», вес 13 кг в том же сообщении, что и
        # брак в лабораторию).
        line_end = (text or "").find("\n", kind[1])
        line_end = len(text or "") if line_end < 0 else line_end
        # Хозяин — ШАПКА раздела, как в расчёте показаний (_owner): «Вес нити
        # после развивки шпулей = 13 кг» под «–251 машина» принадлежит 251-й,
        # хотя подсказка темы несёт другую машину (14.09.2026). Шапки нет —
        # тогда номер внутри строки, затем подсказка темы, и только потом
        # последнее упоминание станка: «помощь Петровского на 151м» — это
        # слова мастера про чужую машину, а не подпись отходов 251-й
        # (прогон 26.09.2026).
        head = _machine_at(heads, kind[0], None)
        machine = (head
                   or _machine_in(machines, kind[0], line_end)
                   or hint
                   or _machine_at(machines, kind[0], None) or "")
        slot = per_machine.setdefault(machine, {})
        value = _to_number(m.group(1)) if m.group(1) else None
        prev = slot.get(kind[2])
        before = prev_at.get((machine, kind[2]))
        same_line = before is not None and (
            (text or "").rfind("\n", 0, before) == (text or "").rfind("\n", 0, num_at))
        if value is not None and same_line and isinstance(prev, (int, float)) \
                and abs(prev - value) > 1e-9:
            # Два РАЗНЫХ числа одного вида в ОДНОЙ СТРОКЕ — это две сдачи, а не
            # правка. «Остаток ниток из шпуль после наладки шпульного стола-
            # 187*3-7 кг; ПЭ 1,2-1,4 кг» (№151, 29.09.2026): оба килограмма
            # лежат после одного маркера вида и названы разными нитками, а
            # раньше 1,4 кг переписывало 7 кг — 7 кг пропадали молча.
            # Числа в РАЗНЫХ строках остаются правкой: «взвешивание нити после
            # развивки шпулей, сухие = 13,6 кг» и строкой ниже «Вес нити после
            # развивки шпулей =13 кг» (№251, 14.09.2026) — это одно и то же
            # взвешивание, переписанное короче, и сложить их значило бы
            # записать станции 26,6 кг там, где сдали 13.
            slot[kind[2]] = round(prev + value, 3)
        elif value is not None or kind[2] not in slot:
            if not (value is None and prev is not None):
                slot[kind[2]] = value
        if value is not None:
            prev_at[(machine, kind[2])] = num_at
        if kind[2] == "прочие" and value is not None:
            after = (text[m.end():].split("\n", 1)[0] or "")
            reason = _other_reason(text[kind[0]:m.end()], after)
            if reason:
                reasons[machine] = reason
    for machine, reason in reasons.items():
        per_machine.setdefault(machine, {})["__reason__"] = reason  # type: ignore
    return per_machine, unknown


# Сколько строк после «Состояние машины:» ещё считаем состоянием.
_STATE_MAX_LINES = 12


def _read_state(text: str, pos: int) -> str:
    """Текст замечания о состоянии машины и полотна, начиная с pos.

    Мастера пишут его ДВУМЯ способами (прогон 10.09.2026):
      • одной строкой — «Состояние машины и полотна: Машина в рабочем
        состоянии.» (ст.151);
      • СПИСКОМ на следующих строках — «Состояние машины:\n* Полотна чистые…
        \n* Необходимо решить…» (ст.251).
    Прежний разбор брал только остаток текущей строки, поэтому список давал
    пустое состояние: все замечания по 251-й (расширенные шпули, посторонний
    шум, перекос осадного вала, отклеилась лента) терялись из отчёта и из 1С.

    Читаем строки до тех пор, пока это маркеры списка (*, -, •, цифры со
    скобкой/точкой) или продолжение текста; останавливаемся на заголовке
    другого блока («Сдаваемые отходы», «–N», «Конец/начало смены»).
    """
    body = (text or "")[pos:]
    lines = body.split("\n")
    first = lines[0]
    first = first.split(":", 1)[1] if ":" in first else first
    first = first.strip(" .;–—-")
    out: List[str] = []
    if first:
        out.append(first)
    for line in lines[1:_STATE_MAX_LINES]:
        stripped = line.strip()
        if not stripped:
            continue
        low = stripped.lower()
        if (low.startswith("сдава") or _HEAD_RE.search(low)
                or _SECTION_HEAD_RE.match(stripped)
                or _STATE_RE.search(low)):
            break
        # строка списка или продолжение текста
        cleaned = re.sub(r"^[*•·◦\-–—]+\s*", "", stripped)
        cleaned = re.sub(r"^\d{1,2}[).]\s*", "", cleaned)
        if not cleaned:
            continue
        out.append(cleaned.strip(" .;–—-"))
        if len(out) >= _STATE_MAX_LINES:
            break
    return "; ".join(x for x in out if x)


def parse_blocks(text: str,
                 machine_hint: Optional[str] = None,
                 source: Optional[int] = None) -> List[MachineRemains]:
    """Достать из текста блоки «остатки и отходы». Ничего не считает.

    machine_hint — номер станка, известный ТОЧНО (заголовок обсуждения в
    Мессенджере). Он слабее номера, названного в самом тексте рядом с цифрами,
    но сильнее догадок: в блоке номер может быть не написан вовсе.
    """
    text = normalize_text(text)
    if not text.strip():
        return []
    machines = _machine_positions(text)
    counters = _counter_positions(text)
    wastes = _waste_positions(text)
    # Отходы и «состояние машины» обрывают замер: подписи внутри них («после
    # подмены на машине») — не показания счётчика.
    heads = _section_head_positions(text)
    barriers = sorted([w[0] for w in wastes]
                      + [m.start() for m in _WASTE_HEAD_RE.finditer(text)]
                      + [m.start() for m in _STATE_RE.finditer(text)]
                      + [at for at, _n in heads])

    blocks: Dict[str, MachineRemains] = {}
    order: List[str] = []

    def _slot(machine: Optional[str]) -> MachineRemains:
        key = machine or ""
        if key not in blocks:
            blocks[key] = MachineRemains(machine=machine or None,
                                         waste={}, counters={})
            if source is not None:
                blocks[key].sources.append(source)
            order.append(key)
        return blocks[key]

    def _owner(start: int, end: int) -> Optional[str]:
        """Чей этот замер.

        Сначала ШАПКА раздела выгрузки («–251»): весь замер лежит в одном
        разделе — номера других станков в его тексте это слова мастера про
        чужую машину, а не подписи показаний (прогон 25.08.2026, ст.251:
        «Подмена 151 машине 101шт» стояла между двумя замерами 251-й, и весь
        её конец смены уехал на 151; так же 31.08 — «Я отошла к № 321»,
        «ушла на 111 м», «16:54 подмена на 151,251 в работе»).
        Если замера шапка не покрывает (сообщение без разделов — мастер пишет
        «Конец смены машина 321:»), важнее номер, названный ВНУТРИ замера,
        затем точная подсказка темы, и только потом — последнее упоминание
        станка (см. _own_machine).
        """
        head = _machine_at(heads, start, None)
        if head and head == _machine_at(heads, max(start, end - 1), None):
            return head                     # весь замер под одной шапкой раздела
        return _own_machine(machines, head, start, end, machine_hint)

    for start, end, moment in _counter_regions(text, counters, barriers):
        values = _read_counters(text, start, end, counters, barriers)
        if not values and not moment:
            continue
        block = _slot(_owner(start, end))
        if moment:
            block.moment = moment
        # Замер, записанный позже, важнее: последнее слово за мастером.
        block.counters.update(values)

    waste_by_machine, unknown = _read_waste(text, wastes, machines,
                                            machine_hint)
    for machine, kinds in waste_by_machine.items():
        block = _slot(machine or None)
        for key, value in kinds.items():
            if key == "__reason__":
                block.other_reason = value        # type: ignore[assignment]
            elif value is not None or key not in block.waste:
                block.waste[key] = value

    for m in _STATE_RE.finditer(text):
        tail = _read_state(text, m.end())
        if not tail:
            continue
        # «Состояние машины:» — это про станок темы, а не про чужую машину,
        # названную в предыдущем сообщении (26.09.2026: «…на 151м» в 16:16 и
        # вечернее состояние 251-й в 19:00 уехали на 151-ю).
        block = _slot(_own_machine(machines, _machine_at(heads, m.start(), None),
                                   m.start(), m.end() + len(tail), machine_hint))
        block.state = (block.state + " " + tail).strip() \
            if tail not in block.state else block.state

    out = [blocks[key] for key in order if blocks[key].ok]
    if unknown:
        # «N кг» без названного вида отходов терять нельзя. Вешаем на станок,
        # если он в тексте назван; иначе разбор отдаёт их через parse_unknown_kg.
        target = out[0] if out else None
        if target is not None:
            for kg in unknown:
                if kg not in target.unknown_kg:
                    target.unknown_kg.append(kg)
    return out


def parse_unknown_kg(text: str, machine_hint: Optional[str] = None
                     ) -> List[Tuple[Optional[str], str]]:
    """«N кг», названные в тексте без вида отходов: [(станок, «11,0 кг»), …].

    Нужны, когда по станку кроме этих килограммов ничего нет: блока не будет, а
    сказать про них надо (ст.251 за 08.09: «Вес срезанных протяжных = 11,0 кг»).
    """
    text = normalize_text(text)
    if not text.strip():
        return []
    machines = _machine_positions(text)
    wastes = _waste_positions(text)
    ranges = [(r.start(), r.end())
              for r in _WEIGHT_RANGE_RE.finditer(text)]
    out: List[Tuple[Optional[str], str]] = []
    for m in _KG_RE.finditer(text):
        if not m.group(1):
            continue
        if _is_stock_weight(text, m.start(), ranges):
            continue     # вес паковок с сырьём, а не заявленные отходы
        if _APPROX_WEIGHT_RE.search(text[:m.start()]):
            continue     # вес назван примерно — сдачи за смену тут нет
        if _is_lab_transfer(text, m.start()):
            continue     # вес брака, переданного в лабораторию — не отходы смены
        if _is_described_weight(text, m.start()):
            continue     # пример записи или размер бобины в скобках, не сдача
        if any(fin <= m.start() and m.start() - fin <= _NEAR
               for _at, fin, _key in wastes):
            continue
        out.append((_machine_at(machines, m.start(), machine_hint),
                    f"{m.group(1).strip()} кг"))
    return out


def _already_counted(block: MachineRemains, kg: str) -> bool:
    """Это же число уже стоит в отходах станка — второй раз просить нельзя.

    22.09.2026, ст.151: строку бланка «При подмене шпулярника пэ 1,2 - 5,2кг»
    парсер учёл, а та же сдача, описанная своими словами («Упаковка и
    взвешивание отходов ПЭ1,2 после замены шпулярника = 5,2 кг»), выходила
    предупреждением «вид отходов не назван — в учёт не попало». Слово «не
    попало» при этом врёт: килограммы в учёте стоят.
    """
    # Пробел после запятой — артефакт выгрузки («Вес отходов после подмены
    # 10, 4кг», ст.111 за 21.09.2026): без сборки числа обратно сравнение
    # считало бы 10,0 и вопрос про висел бы снова.
    kg = re.sub(r"([.,])[ \t\u00a0]+(?=\d)", r"\1", kg or "")
    found = re.search(r"\d[\d.,]*", kg)
    if not found:
        return False
    try:
        value = float(found.group(0).replace(",", ".").rstrip(".,"))
    except ValueError:
        return False
    return any(isinstance(v, (int, float)) and v and abs(v - value) < 0.005
               for v in block.waste.values())


# ─────────────────── бланк заполнен со смещением (#58) ───────────────────
# 24.09.2026, ст.111: «Ср.сч. - _1____ из 2____» и «Срез - _614__ из _2700___».
# По всем остальным сохранённым сменам срез — это ШТУКИ (план 1…7), а средний
# счётчик — узлы с планом в тысячи (760, 1450, 14500, 14800). Значит строки
# бланка сдвинуты. Менять цифры местами нельзя: это выдуманное показание,
# а правило HANDOFF — «нет данных вместо выдуманных». Поэтому числа остаются
# как написал мастер, а отчёт ЗАДАЁТ ему вопрос.
# Выше этого плана срез быть не может: станок не режет полотно сотнями.
_SLICE_PLAN_MAX = 20.0
# Ни один средний счётчик за смену не планирует меньше этого.
_COUNTER_PLAN_MIN = 50.0


def _swapped_blank_lines(block: MachineRemains) -> List[str]:
    """Вопрос мастеру, если строки «Ср.сч.» и «Срез» перепутаны местами."""
    srez, srez_plan = block.counter("срез"), block.counter_of("срез")
    sred, sred_plan = block.counter("средний_счётчик"), \
        block.counter_of("средний_счётчик")
    if not all((srez, srez_plan, sred, sred_plan)):
        return []
    if srez_plan <= _SLICE_PLAN_MAX or sred_plan >= _COUNTER_PLAN_MIN:
        return []
    return [f"№{block.machine}: в бланке перепутаны строки «Ср.сч.» и «Срез» — "
            f"средний счётчик {_num(sred)} из {_num(sred_plan)}, а срез "
            f"{_num(srez)} из {_num(srez_plan)}. Срезы пишут единицами, средний "
            f"счётчик — тысячами. Оставили как у мастера; скажите, какая строка "
            f"верная."]


# ─────────────────── подозрительный общий счётчик (#59) ───────────────────
# 14.09–16.09.2026, ст.321: мастер пишет «Общ сч 1200807», хотя по накопленным
# сменам счётчик станка идёт 118526 (10.09) → 123061 (21.09). Лишний ноль.
# Сверять только с СОСЕДНЕЙ сменой нельзя: опечатка повторена в трёх сменах
# подряд, и соседнее показание такое же испорченное (проверка counter_check
# сознательно молчит, когда мастер повторил число 2+ раза).
#
# Общий счётчик — одометр: он не убывает никогда, и за одну смену не растёт в
# разы. Поэтому проверяем число с ОБОИХ сторон — по всем сохранённым сменам
# этого станка до и после, — а не по одной соседней.
#
# Число НЕ подменяем: правая цифра здесь — вопрос к владельцу («сверьте с
# журналом»), а не вывод из регулярки. HANDOFF: «нет данных вместо выдуманных».
# Порог мягкий: подозрение поднимаем при расхождении в 1,5 раза и только на
# числах, где лишний ноль физически помещается.
_JUMP_RATIO = 1.5
_JUMP_MIN = 1000.0


def _day_order(date: str) -> Tuple[int, int, int]:
    """Порядок смены по дате «ДД.ММ.ГГГГ» (непонятная строка — в самое начало)."""
    try:
        dd, mm, yy = str(date).split(".")
        return (int(yy), int(mm), int(dd))
    except ValueError:
        return (0, 0, 0)


def odometer_readings(day: DayRemains) -> Dict[str, float]:
    """Общие счётчики станков смены: {нормализованный номер: показание}.

    Показание с планом («1000 из 1450» у ст.98 за 21.09) не берём: это счёт
    одного среза, приехавший под метку общего счётчика, — с одометром его не
    сравнивают.
    """
    out: Dict[str, float] = {}
    for block in day.machines:
        fact, of = block.counters.get("общий_счётчик") or (None, None)
        if fact is None or of is not None:
            continue
        out[machine_rates._norm_key(block.machine)] = fact
    return out


def shift_odometers(date: str) -> List[Tuple[str, Dict[str, float]]]:
    """Общие счётчики всех сохранённых смен, кроме этой. Регулярки, без ИИ."""
    from . import shift_store
    out: List[Tuple[str, Dict[str, float]]] = []
    for row in shift_store.list_days():
        other = row[0]
        if other == date:
            continue
        day = build_day_remains(
            other, messages=shift_store.load_day(other).get("messages") or [])
        out.append((other, odometer_readings(day)))
    return out


def counter_chronology_warnings(date: str, day: DayRemains,
                                neighbours: Optional[List] = None) -> List[str]:
    """Вопрос владельцу, если общий счётчик противоречит хронологии смен.

    neighbours — [(дата смены, odometer_readings)] других сохранённых смен;
    по умолчанию читаем накопитель (см. shift_odometers).
    """
    readings = odometer_readings(day)
    if not readings:
        return []
    if neighbours is None:
        neighbours = shift_odometers(date)
    this = _day_order(date)
    ordered = sorted(neighbours, key=lambda item: _day_order(item[0]))
    before = [(d, v) for d, v in ordered if _day_order(d) < this]
    after = [(d, v) for d, v in ordered if _day_order(d) > this]

    out: List[str] = []
    for block in day.machines:
        fact, of = block.counters.get("общий_счётчик") or (None, None)
        if fact is None or of is not None:
            continue
        key = machine_rates._norm_key(block.machine)
        # Ближайшее ОТЛИЧАЮЩЕЕ показание: серия одинаковых чисел — это одна и та
        # же опечатка мастера, а не доказательство, что счётчик такой.
        prev = next(((d, v[key]) for d, v in reversed(before)
                     if key in v and v[key] != fact), None)
        nxt = next(((d, v[key]) for d, v in after
                    if key in v and v[key] != fact), None)
        # Обе стороны хронологии — одно и то же противоречие: одометр не
        # убывает никогда. Берём самое показательное расхождение.
        suspects = []
        if prev and fact < prev[1] and min(fact, prev[1]) >= _JUMP_MIN:
            suspects.append((
                prev[1] / max(fact, 1.0),
                f"в смене {prev[0]} стояло {_num(prev[1])}, а одометр назад не "
                f"отматывается"))
        if nxt and fact > nxt[1] and min(fact, nxt[1]) >= _JUMP_MIN:
            suspects.append((
                fact / max(nxt[1], 1.0),
                f"в смене {nxt[0]} счётчик уже показывает {_num(nxt[1])} — "
                f"ниже него он упасть не мог"))
        strong = [s for s in suspects if s[0] >= _JUMP_RATIO]
        if not strong:
            continue
        ratio, phrase = max(strong, key=lambda s: s[0])
        out.append(
            f"№{block.machine}: общий счётчик {_num(fact)} — {phrase}. "
            f"Расхождение в {round(ratio)} раз, похоже на лишний или пропущенный "
            f"ноль. Число оставлено как в сообщении мастера — сверьте с "
            f"журналом станка.")
    return out


# ─────────────────── сборка по смене (из накопленных сообщений) ───────────────────

def _merge(into: MachineRemains, other: MachineRemains) -> None:
    """Долить второй блок по тому же станку в первый.

    Мастер может прислать шапку показаний и отходы разными сообщениями (или
    дослать уточнение). Затираем только тем, что реально заполнено: пришедшее
    позже считаем свежим — «считаем как есть», последнее слово за мастером.
    """
    for key, val in other.counters.items():
        if val[0] is not None or val[1] is not None:
            into.counters[key] = val
    for kg in other.unknown_kg:
        if kg not in into.unknown_kg:
            into.unknown_kg.append(kg)
    for key, val in other.waste.items():
        if val is not None:
            into.waste[key] = val
    if other.state:
        into.state = (into.state + " " + other.state).strip() \
            if other.state not in into.state else into.state
    if other.other_reason and not into.other_reason:
        into.other_reason = other.other_reason
    if other.moment and not into.moment:
        into.moment = other.moment
    for src in other.sources:
        if src not in into.sources:
            into.sources.append(src)


def build_day_remains(date: str, messages: Optional[List[dict]] = None,
                      reports: Optional[List] = None) -> DayRemains:
    """Остатки и отходы за смену по накопленным сообщениям. Без ИИ.

    messages — записи накопителя (`shift_store.load_day(date)["messages"]`).
    Если не переданы, читаем накопитель сами.
    reports — готовые отчёты по станкам: из них берём фамилию оператора и
    отмечаем станки, по которым блок отходов не прислали.
    """
    if messages is None:
        from . import shift_store
        messages = shift_store.load_day(date).get("messages") or []

    day = DayRemains(date=date)
    by_key: Dict[str, MachineRemains] = {}
    no_machine: List[MachineRemains] = []
    unattributed: List[Tuple[Optional[str], str]] = []

    # Станок, на котором закончилось ПРЕДЫДУЩЕЕ сообщение. Длинную переписку
    # режет на части по 4096 знаков, и разрез попадает посередине обсуждения:
    # хвост без заголовка принадлежит тому же станку (прогон 10.09.2026 —
    # «–251» в первом сообщении, «Конец смены … 278755» во втором).
    carried: Optional[str] = None

    for msg in messages:
        index = msg.get("index")
        texts = [msg.get("text") or ""]
        for item in (msg.get("photos_meta") or []):
            if item.get("ocr_text"):
                texts.append(item["ocr_text"])
        for text in texts:
            # Тот же текст, что уходит в ИИ: выгрузка чата теряет переводы
            # строк, и «Подмена 4 из 5\n16:38 пуск» приезжает как «из 516:38»
            # (см. shift_store.split_glued_text).
            try:
                from . import shift_store as _ss
                text = _ss.split_glued_text(text)
            except Exception:                     # pragma: no cover
                pass                              # без накопителя — как есть
            # Явный станок сообщения важнее всего; если его нет — берём
            # станок, на котором оборвалось предыдущее сообщение (разрез
            # посередине обсуждения). Заголовок раздела ВНУТРИ текста
            # переопределит подсказку сам — см. _machine_in в parse_blocks.
            hint = msg.get("machine") or carried
            unattributed += parse_unknown_kg(text, machine_hint=hint)
            for block in parse_blocks(text, machine_hint=hint,
                                      source=index):
                key = machine_rates._norm_key(block.machine)
                if not key:
                    no_machine.append(block)
                    continue
                if key in by_key:
                    _merge(by_key[key], block)
                else:
                    by_key[key] = block
                    day.machines.append(block)

        # Запоминаем станок последнего раздела — для хвоста следующего
        # сообщения (см. carried выше).
        tail = last_section_machine(msg.get("text") or "")
        if tail:
            carried = tail

    # Блок без номера станка молчать нельзя: цифры есть, а к кому отнести —
    # неизвестно. Если за смену станок ровно один, отдаём ему; иначе говорим
    # словами (решение — за человеком, как он и просил).
    for block in no_machine:
        if len(by_key) == 1:
            only = next(iter(by_key.values()))
            _merge(only, block)
            day.warnings.append(
                f"блок отходов без номера станка отнесён к №{only.machine} "
                f"(это единственный станок с остатками за смену)")
        else:
            day.machines.append(block)
            day.warnings.append(
                "прислан блок остатков/отходов без номера станка — "
                f"учтён отдельной строкой (сдано {_num(block.waste_total)} кг). "
                "Пришлите номер станка, и я перенесу.")

    # Килограммы, названные без вида отходов, в сумму не идут — но и молчать
    # о них нельзя: скорее всего мастер сдал их, просто написал своими словами.
    seen: List[Tuple[str, str]] = []
    for machine, kg in unattributed:
        pair = (machine or "", kg)
        if pair in seen:
            continue
        seen.append(pair)
        block = by_key.get(machine_rates._norm_key(machine)) if machine else None
        if block is not None and _already_counted(block, kg):
            continue
        num = machine or "станок не указан"
        day.warnings.append(
            f"№{num}: в сообщении есть «{kg}», но вид отходов не назван — в "
            f"учёт не попало. Скажите, к какому виду отнести, или пусть мастер "
            f"пишет строкой бланка.")

    # Перепутанные строки бланка («Ср.сч.» вместо «Срез»): цифры как у мастера,
    # вопрос — в предупреждения (см. _swapped_blank_lines).
    for block in day.machines:
        day.warnings.extend(_swapped_blank_lines(block))

    if reports:
        for r in reports:
            key = machine_rates._norm_key(getattr(r, "machine", None))
            block = by_key.get(key)
            if block is not None and not block.operator:
                block.operator = getattr(r, "operator", None)
    day.machines.sort(key=_machine_sort_key)
    return day


def _machine_sort_key(block: MachineRemains):
    """Станки по номеру: числовые по возрастанию, буквенные — в конец."""
    key = machine_rates._norm_key(block.machine)
    if key.isdigit():
        return (0, int(key), "")
    return (1, 0, key)


def _worked(report) -> bool:
    """По станку в переписке вообще что-то было.

    Нулевые строки парка (601, 14тр — «нет данных о работе») в отчёт по
    отходам напоминанием не ставим: мастер не присылал блок не потому, что
    забыл, а потому, что станок в смене не жил.
    """
    if getattr(report, "not_parsed", False):
        return True
    if getattr(report, "lines", None) or getattr(report, "tech_stops", None):
        return True
    return bool(getattr(report, "operator", None))


def machines_without_remains(day: DayRemains, reports: Optional[List]) -> List[str]:
    """Станки смены, по которым блок остатков/отходов не прислали."""
    if not reports:
        return []
    out: List[str] = []
    for r in reports:
        num = str(getattr(r, "machine", "") or "").strip()
        if not num or not _worked(r):
            continue
        if day.by_machine(num) is None and num not in out:
            out.append(num)
    return out


def format_remains_digest(day: DayRemains, limit: int = 12) -> str:
    """Короткая сводка по отходам для чата (одна строка на станок)."""
    if not day.ok:
        return ""
    # Разметки Telegram здесь больше нет: текст читает страница, а она показывает
    # строки как есть, и «<b>» человек увидел бы буквами.
    out = [f"♻️ Сдаваемые отходы за {day.date}: "
           f"{_num(day.waste_total)} кг"]
    for block in day.machines[:limit]:
        num = block.machine or "станок не указан"
        if not block.has_waste:
            # Ноль писать нельзя: мастер прислал показания, а блок отходов —
            # нет. «0 кг» читалось бы как «сдал ноль», а это разные вещи.
            out.append(f"• №{num} — отходы не указаны")
            continue
        line = f"• №{num} — {_num(block.waste_total)} кг"
        kinds = block.waste_kinds_text
        if kinds:
            line += f" ({kinds})"
        if block.state:
            line += " ⚠️ есть замечание по машине"
        out.append(line)
    if len(day.machines) > limit:
        out.append(f"…и ещё станков: {len(day.machines) - limit}")
    return "\n".join(out)
