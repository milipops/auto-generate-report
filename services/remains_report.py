# «- 12 345,5 кг», «12345», «0». Пробелы внутри числа бывают у мастеров.
# Минус НЕ забираем: тире в блоке — это разделитель «имя - значение», а не
# знак (отрицательных килограммов и показаний счётчика не бывает).
# Пробелы внутри числа мастера пишут («12 345»), а ПЕРЕВОД СТРОКИ — уже не
# часть числа: «Ср.сч 250узл. из 1400\n4 ср.» матчилось как «1400\n4»,
# float() падал, и «из 1400» терялось (прогон 10.09.2026, ст.98).
# ⚠️ Пробел считается разделителем тысяч ТОЛЬКО если за ним ровно ТРИ цифры и
# дальше не идёт ещё одна цифра. Иначе жадный класс [\d \t]* склеивал число со
# следующим значением: прогон 16.09.2026, ст.98 — мастер написал
# «Общий сч.21453550 7срезов» (счётчик, затем через пробел «7 срезов»),
# регулярка взяла «21453550 7», и в лист «Остатки» уехало показание 214535507
# вместо 21453550. Группы по три цифры оставляют «12 345» и «21 453 550»
# целыми, а «21453550 7срезов» разделяют на 21453550 и 7.
_NUM_RE = re.compile(
    r"\d+(?:[ \t \u2007\u202f]\d{3}(?!\d))*(?:[.,]\d+)?")
# Показание счётчика читается тем же правилом разрядов, но с ещё одной
# оговоркой: группа из трёх цифр НЕ приклеивается, если в той же строке за
# ней идёт слово. Прогон 22.09.2026, ст.151: «Подмена 4 из 4 212 протяжных
# узлов» дала план 4212 — это отдельное число со своей подписью; так же
# «3Ср из 4 200Уз из 1450» (21.09, ст.98). Настоящие разряды мастер пишет в
# конце строки: «ср.сч- 2970 из 2 700» (24.09, ст.111) и «Общий счёт:
# 717 692» (25.08) — после них перевод строки, и группировка остаётся.
# То же правило для ДРОБНОЙ части: счётчики узлов целые, а «480,4 срез из 4»
# (прогон 02.09.2026, ст.321) — это «из 480», затем «4 срез из 4»: запятая
# здесь разделила два показания, а не десятичная.
_COUNTER_NUM_RE = re.compile(
    r"\d+(?:[ \t\u00a0\u2007\u202f]\d{3}(?!\d)"
    r"(?![ \t\u00a0\u2007\u202f]*[^\W\d_]))*"
    r"(?:[.,]\d+(?!\d)(?![ \t\u00a0\u2007\u202f]*[^\W\d_]))?",
    re.IGNORECASE)
# Заголовок блока: «Конец смены:», «Конец(начало) смены», «Начало смены:».
# Перед «конец/начало смены» НЕ должно быть буквы, цифры или двоеточия:
# «07:07начало смены м прием ее» (прогон 10.09.2026, ст.251) открывало ложный
# замер и разрывало настоящие показания машины на два региона.
_HEAD_RE = re.compile(
    r"(?<![\w\d:])(конец|начало)\s*(?:\(\s*(?:конец|начало)\s*\))?\s*смены",
    re.IGNORECASE)
_WASTE_HEAD_RE = re.compile(r"сдава\w*\s+отход|отходы\s*(?:за\s+смену)?\s*:",
                            re.IGNORECASE)
_STATE_RE = re.compile(r"состояни\w*\s+(?:машины|станка)", re.IGNORECASE)
# «251 машина», «№251», «машина 121», «ст. 98» — номер станка в блоке.
# Третья альтернатива — ЗАГОЛОВОК РАЗДЕЛА экспорта переписки: «–151», «-98»
# на отдельной строке. Так бот получает обсуждения из Telegram-экспорта
# (прогон 09.09.2026): каждый станок — раздел с шапкой «–N». Без неё замеры
# 321/111/98 оказывались «без станка», сливались в один блок и приписывались
# №151 (единственное «на 151 м» внутри текста), а показания 98-й перезатирали
# данные 151-й — в отчёте у 151 стоял счётчик 21378750 от 98-й машины.
_MACHINE_RE = re.compile(
    r"(?:№\s*|\bмашина\s*|\bстанок\s*|\bст\.?\s*)(\d{2,3})\b|"
    r"\b(\d{2,3})\s*(?:машина|машины|машине|м\b|станок)|"
    # Прогон 10.09.2026: экспорт склеивает абзацы, и перед тире заголовка
    # стоит пробел/точка, а не перевод строки («…выхода полотна. –251\nЮлия
    # Черныш…»). Требовать ^|\n нельзя — секция 251-й не находилась, и ВСЕ её
    # показания уезжали на №151. Достаточно, чтобы перед тире не было
    # буквы/цифры, а номер заканчивал строку.
    r"(?<![\w\d])[–—-]\s*(\d{2,3})\s*(?=\n|$)", re.IGNORECASE)
# Те же шапки разделов отдельным паттерном: они РАЗДЕЛЯЮТ замер одного станка
# и замер следующего (барьер для _counter_regions), иначе показания соседних
# разделов склеиваются в один кластер.
# Слово «машина» после номера — часть шапки («–98 машина», прогон 14.09.2026):
# без него шапка не находилась, кластер «конец смены» предыдущего станка
# дотягивался до показаний 98-й, и более полный чужой замер («Навито 11 из 180»)
# вытеснял настоящие 160 шпуль.
_SECTION_HEAD_RE = re.compile(
    r"(?<![\w\d])[–—-]\s*(\d{2,3})\s*(?:машина|машины|машине)?\s*(?=\n|$)",
    re.IGNORECASE)


def _to_number(text: str,
               pattern: Optional["re.Pattern"] = None) -> Optional[float]:
    """«12 345,5 кг» → 12345.5. Прочерк/пусто → None (мастер не заполнил)."""
    m = (pattern or _NUM_RE).search(text or "")
    if not m:
        return None
    raw = re.sub(r"[ 	   ]", "", m.group(0)).replace(",", ".")
    try:
        val = float(raw)
    except ValueError:
        return None
    return val


def _to_counter(text: str) -> Optional[float]:
    """Число ПОКАЗАНИЯ счётчика: «4 212 узлов» → 4, а «2 700» → 2700.

    Тот же разбор чисел, что и у _to_number, но группы разрядов проверяются
    строже — см. _COUNTER_NUM_RE.
    """
    return _to_number(text, _COUNTER_NUM_RE)


def _num(value: Optional[float]) -> str:
    """Число для человека: 12.0 → «12», 0.5 → «0,5», None → «—».

    Через %g нельзя: показание счётчика 21140500 превращается в «2,11405e+07».
    """
    if value is None:
        return "—"
    val = round(float(value), 3)
    if val == int(val):
        return str(int(val))
    return f"{val}".rstrip("0").rstrip(".").replace(".", ",")


