class AIExtractError(RuntimeError):
    """Ошибка обращения к ИИ или разбора его ответа."""


class AIRetryableError(AIExtractError):
    """Шлюз или поток не справились СЕЙЧАС — тот же запрос стоит повторить.

    Два симптома: соединение со шлюзом закрылось после «размышлений», не отдав
    ответ (finish_reason/stop_reason не «length»/«max_tokens», текста 0), или
    шлюз ответил 5xx/429. И то, и другое живёт секунды-минуты, и повтор обычно
    проходит. Не путать с нехваткой токенов: там повтор бесполезен.
    """


# Ответы шлюза, которые ничего не говорят о данных и живут секунды: лимит
# запросов (429), таймаут источника и 5xx (в т.ч. Cloudflare 52x). Прогон
# 21.09.2026: станок №98 поймал HTTP 502 и два обрыва соединения подряд — все
# три попытки ушли за 0,2 с, потому что повтор не ждал, пока шлюз оправится,
# и отчёт вышел без данных по 98 (35 минут прогона насмарку).
_TRANSIENT_HTTP = frozenset({408, 429, 500, 502, 503, 504, 520, 521, 522, 524})

# Секунды паузы перед переспросом станка (умножаются на номер повтора). Тесты
# ставят 0: здесь важна сама попытка, а не ожидание.
MACHINE_RETRY_PAUSE_S = 8.0


def _http_error(code: int, body: str) -> AIExtractError:
    msg = f"HTTP {code} от ИИ: {body[:500]}"
    return (AIRetryableError(msg) if code in _TRANSIENT_HTTP
            else AIExtractError(msg))


def _network_error(reason: object) -> AIExtractError:
    """Соединение оборвалось/не установилось — данных это не касается."""
    return AIRetryableError(f"Сеть недоступна: {reason}")


def _http_post(url: str, headers: Dict[str, str], payload: Dict[str, Any],
               timeout: int = 300) -> Dict[str, Any]:
    data = json.dumps(payload).encode("utf-8")
    # Cloudflare перед некоторыми шлюзами (agentrouter.org и т.п.) режет
    # клиентов без «браузерной» подписи и отдаёт 403 error code 1010.
    # Дефолтный User-Agent urllib («Python-urllib/…») — как раз такой случай,
    # поэтому шлём обычный браузерный, если вызывающий не задал свой.
    headers = dict(headers)
    headers.setdefault(
        "User-Agent",
        "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 "
        "(KHTML, like Gecko) Chrome/126.0.0.0 Safari/537.36",
    )
    headers.setdefault("Accept", "application/json")
    req = urllib.request.Request(url, data=data, headers=headers, method="POST")
    try:
        with urllib.request.urlopen(req, timeout=timeout) as resp:
            return json.loads(resp.read().decode("utf-8"))
    except urllib.error.HTTPError as e:
        body = e.read().decode("utf-8", "replace")
        raise _http_error(e.code, body) from e
    except (TimeoutError, socket.timeout) as e:
        raise AIExtractError(
            f"ИИ не ответил за {timeout} с (таймаут). Модель с «thinking» "
            f"отвечает медленно — можно увеличить таймаут или взять модель "
            f"без размышлений."
        ) from e
    except urllib.error.URLError as e:
        # У socket-таймаута reason тоже приходит сюда как timeout.
        if isinstance(getattr(e, "reason", None), (TimeoutError, socket.timeout)):
            raise AIExtractError(
                f"ИИ не ответил за {timeout} с (таймаут)."
            ) from e
        raise _network_error(e.reason) from e


def _http_post_stream(url: str, headers: Dict[str, str],
                      payload: Dict[str, Any],
                      timeout: int = 300) -> List[str]:
    """POST со stream=true. Возвращает список строк SSE-данных (без 'data: ').

    Потоковый режим спасает от Cloudflare 524 (origin_response_timeout):
    модель шлёт ответ по кусочкам сразу, соединение не «молчит» 120 с.
    """
    body = dict(payload)
    body["stream"] = True
    data = json.dumps(body).encode("utf-8")
    headers = dict(headers)
    headers.setdefault(
        "User-Agent",
        "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 "
        "(KHTML, like Gecko) Chrome/126.0.0.0 Safari/537.36",
    )
    headers.setdefault("Accept", "text/event-stream")
    req = urllib.request.Request(url, data=data, headers=headers, method="POST")
    chunks: List[str] = []
    try:
        with urllib.request.urlopen(req, timeout=timeout) as resp:
            try:
                for raw in resp:
                    line = raw.decode("utf-8", "replace").strip()
                    if not line or not line.startswith("data:"):
                        continue
                    payload_line = line[len("data:"):].strip()
                    if payload_line == "[DONE]":
                        break
                    chunks.append(payload_line)
            except (TimeoutError, socket.timeout, urllib.error.URLError,
                    ConnectionError, OSError) as e:
                # Соединение оборвалось ПОСРЕДИ потока (частая беда шлюза/Cloudflare
                # с рассуждающими моделями: после «мыслей», до самого ответа).
                # Не теряем то, что успели собрать; вызывающий увидит пустой/
                # обрезанный ответ и повторит запрос (AIRetryableError).
                logger.warning("Поток ИИ оборвался посреди ответа (%s); "
                               "собрано кусков: %d", e, len(chunks))
        return chunks
    except urllib.error.HTTPError as e:
        b = e.read().decode("utf-8", "replace")
        raise _http_error(e.code, b) from e
    except (TimeoutError, socket.timeout) as e:
        raise AIExtractError(f"ИИ не ответил за {timeout} с (таймаут).") from e
    except urllib.error.URLError as e:
        if isinstance(getattr(e, "reason", None), (TimeoutError, socket.timeout)):
            raise AIExtractError(f"ИИ не ответил за {timeout} с (таймаут).") from e
        raise _network_error(e.reason) from e


def _anthropic_content(text: str, images: List[Image],
                       instruction: Optional[str] = None) -> List[Dict[str, Any]]:
    content: List[Dict[str, Any]] = []
    for media_type, b64 in images:
        content.append({
            "type": "image",
            "source": {"type": "base64", "media_type": media_type, "data": b64},
        })
    content.append({"type": "text",
                    "text": (instruction or USER_INSTRUCTION) + text})
    return content


def _openai_content(text: str, images: List[Image],
                    instruction: Optional[str] = None) -> List[Dict[str, Any]]:
    content: List[Dict[str, Any]] = [
        {"type": "text", "text": (instruction or USER_INSTRUCTION) + text}
    ]
    for media_type, b64 in images:
        content.append({
            "type": "image_url",
            "image_url": {"url": f"data:{media_type};base64,{b64}"},
        })
    return content


def _build_url(base: str, endpoint: str) -> str:
    """Собрать адрес запроса, не задваивая путь.

    Пользователь может задать AI_BASE_URL по-разному, и все варианты должны
    работать:
      • только хост         → https://api.b.ai
      • хост с версией       → https://api.b.ai/v1
      • полный эндпоинт с сайта шлюза → https://api.b.ai/v1/chat/completions
    endpoint — канонический хвост, например "/v1/chat/completions" или
    "/v1/messages". Если base уже заканчивается на этот хвост (или на "/v1"),
    ничего не дублируем.
    """
    base = (base or "").rstrip("/")
    endpoint = "/" + endpoint.strip("/")            # нормализуем к "/v1/..."
    if base.endswith(endpoint):
        return base                                  # уже полный адрес
    # База вида ".../v1" — приклеиваем только оставшийся хвост после "/v1".
    if base.endswith("/v1") and endpoint.startswith("/v1/"):
        return base + endpoint[len("/v1"):]
    return base + endpoint


def _raise_empty(reason: Optional[str], reason_chars: int, max_tokens,
                 exhausted: bool) -> None:
    """Пустой ответ: либо реально кончились токены, либо оборвался поток.

    exhausted=True (finish_reason «length» / stop_reason «max_tokens») — модель
    упёрлась в лимит: повтор не поможет, надо поднять AI_MAX_TOKENS. Иначе это
    обрыв потока (reason None/«stop» при 0 текста) — повторяемая ошибка.
    """
    if exhausted:
        logger.warning(
            "ИИ упёрся в лимит токенов: причина=%s, «размышлений»=%d симв., "
            "max_tokens=%s. Поднимите AI_MAX_TOKENS.",
            reason, reason_chars, max_tokens)
        raise AIExtractError(
            "ИИ израсходовал весь лимит max_tokens на размышления и не успел "
            f"дать ответ (причина={reason}, max_tokens={max_tokens}). "
            "Увеличьте AI_MAX_TOKENS.")
    logger.warning(
        "Пустой ответ ИИ из-за обрыва потока: причина=%s, текста=0 симв., "
        "«размышлений»=%d симв. Повторю запрос.", reason, reason_chars)
    raise AIRetryableError(
        f"ИИ вернул пустой ответ — поток оборвался (причина={reason}, "
        "текста 0 симв.). Это не нехватка токенов; повтор обычно проходит.")


def _call_anthropic(text: str, images: List[Image],
                    instruction: Optional[str] = None) -> str:
    s = _settings()
    url = _build_url(s.ai_base_url, "/v1/messages")
    headers = {
        "x-api-key": s.ai_api_key,
        # Некоторые шлюзы (New API и т.п.) ждут ключ в Authorization —
        # шлём оба заголовка, лишний просто игнорируется.
        "Authorization": f"Bearer {s.ai_api_key}",
        "anthropic-version": "2023-06-01",
        "content-type": "application/json",
    }
    payload = {
        "model": s.ai_model,
        "max_tokens": s.ai_max_tokens,
        "system": SYSTEM_PROMPT,
        "messages": [{"role": "user",
                      "content": _anthropic_content(text, images,
                                                    instruction)}],
    }
    # Потоковый режим: спасает от Cloudflare 524, когда модель думает долго.
    text_out: List[str] = []
    reason_chars = 0
    stop_reason = None
    for chunk in _http_post_stream(url, headers, payload, timeout=s.ai_timeout):
        try:
            obj = json.loads(chunk)
        except json.JSONDecodeError:
            continue
        if obj.get("type") == "content_block_delta":
            delta = obj.get("delta") or {}
            if delta.get("type") == "text_delta":
                text_out.append(delta.get("text", ""))
            elif delta.get("type") == "thinking_delta":
                reason_chars += len(delta.get("thinking", ""))
        elif obj.get("type") == "message_delta":
            stop_reason = (obj.get("delta") or {}).get("stop_reason") or stop_reason
    out = "".join(text_out)
    if not out.strip():
        _raise_empty(stop_reason, reason_chars, s.ai_max_tokens,
                     exhausted=(stop_reason == "max_tokens"))
    else:
        logger.info("ИИ-ответ: %d симв., stop_reason=%s", len(out), stop_reason)
    return out


def _call_openai(text: str, images: List[Image],
                 instruction: Optional[str] = None) -> str:
    s = _settings()
    url = _build_url(s.ai_base_url, "/v1/chat/completions")
    headers = {
        "Authorization": f"Bearer {s.ai_api_key}",
        "content-type": "application/json",
    }
    payload = {
        "model": s.ai_model,
        "max_tokens": s.ai_max_tokens,
        "messages": [
            {"role": "system", "content": SYSTEM_PROMPT},
            {"role": "user",
             "content": _openai_content(text, images, instruction)},
        ],
    }
    # Потоковый режим: спасает от Cloudflare 524, когда модель думает долго.
    text_out: List[str] = []
    reason_chars = 0            # сколько «размышлений» (reasoning) пришло
    finish_reason = None
    for chunk in _http_post_stream(url, headers, payload, timeout=s.ai_timeout):
        try:
            obj = json.loads(chunk)
        except json.JSONDecodeError:
            continue
        choices = obj.get("choices") or []
        if not choices:
            continue
        ch0 = choices[0]
        if ch0.get("finish_reason"):
            finish_reason = ch0["finish_reason"]
        delta = ch0.get("delta") or {}
        piece = delta.get("content")
        if piece:
            text_out.append(piece)
        # Некоторые шлюзы отдают ответ не по кускам, а целиком в message.
        msg = ch0.get("message") or {}
        if msg.get("content") and not delta:
            text_out.append(msg["content"])
        # Рассуждающие модели (opus и т.п.) шлют «мысли» отдельным полем —
        # они съедают max_tokens, но в JSON-ответ не идут. Считаем их объём,
        # чтобы объяснить пустой ответ.
        for rk in ("reasoning_content", "reasoning"):
            rv = delta.get(rk) or msg.get(rk)
            if isinstance(rv, str):
                reason_chars += len(rv)
    out = "".join(text_out)
    if not out.strip():
        _raise_empty(finish_reason, reason_chars, s.ai_max_tokens,
                     exhausted=(finish_reason == "length"))
    else:
        logger.info("ИИ-ответ: %d симв., причина завершения=%s",
                    len(out), finish_reason)
    return out


def _extract_json(content: str) -> Dict[str, Any]:
    """Достать JSON-объект из ответа модели (возможны ```json ... ``` и текст)."""
    text = content.strip()
    if not text:
        raise AIExtractError(
            "ИИ вернул пустой ответ (0 символов). Обычно это значит, что "
            "рассуждающая модель израсходовала весь лимит max_tokens на "
            "размышления. Увеличьте AI_MAX_TOKENS (напр. до 16000–32000) "
            "или разбейте смену на меньшие части.")
    if text.startswith("```"):
        text = text.split("```", 2)[1]
        if text.lstrip().lower().startswith("json"):
            text = text.lstrip()[4:]
    start, end = text.find("{"), text.rfind("}")
    if start == -1 or end == -1:
        raise AIExtractError(f"В ответе ИИ нет JSON: {content[:300]}")
    try:
        return json.loads(text[start:end + 1])
    except json.JSONDecodeError as e:
        raise AIExtractError(f"Не удалось разобрать JSON ИИ: {e}") from e


def _normalize(data: Dict[str, Any]) -> Dict[str, Any]:
    """Привести ответ ИИ к ожидаемой структуре сменного отчёта."""
    machines = data.get("machines") or []
    for m in machines:
        m.setdefault("machine", None)
        m.setdefault("operator", None)
        m.setdefault("operator2", None)
        m.setdefault("operator2_start", None)
        m.setdefault("operator_start", None)
        m.setdefault("first_info_time", None)
        m.setdefault("brand", None)
        m.setdefault("operator_shift_end", None)
        m.setdefault("operator_norm_hours", None)
        m.setdefault("cuts", None)
        m.setdefault("subs_count", None)
        m.setdefault("subs_fio", None)
        # Обратная совместимость: если счётчики пришли на самом станке.
        lines = m.get("lines")
        if not isinstance(lines, list) or not lines:
            lines = []
            if m.get("counter_start") or m.get("counter_end"):
                lines = [{
                    "assortment": m.get("assortment"),
                    "client": m.get("client"),
                    "order_no": m.get("order_no"),
                    "panels": m.get("panels"),
                    "counter_start": m.get("counter_start"),
                    "counter_end": m.get("counter_end"),
                }]
        for ln in lines:
            for key in ("assortment", "client", "order_no", "panels",
                        "counter_start", "counter_end"):
                ln.setdefault(key, None)
            # Признак «начального показания в переписке нет, взято из середины
            # смены» — по нему отчёт предупредит, что часы станка занижены
            # (прогон 01.09, ст.321: 115423 из середины вместо 115329 на 07:00).
            ln["counter_start_mid_shift"] = bool(
                ln.get("counter_start_mid_shift"))
        m["lines"] = lines
        events = m.get("events") or []
        for ev in events:
            kind = (ev.get("kind") or ev.get("category") or "").strip().lower()
            ev["kind"] = kind
            ev.setdefault("start", None)
            ev.setdefault("end", None)
            ev.setdefault("reason", ev.get("label") or ev.get("text") or "")
            ev.setdefault("performer", None)
            # Плавающий обед (16.09.2026): признак «станок на перерыв приняли,
            # машина не останавливалась». Код снимает по нему строку «простой
            # обед». Любое истинное значение модели приводим к bool, отсутствие
            # поля — к None (значит признак не назван).
            kept = ev.get("machine_kept_running")
            ev["machine_kept_running"] = (
                None if kept is None else bool(kept))
            # Номер другого станка приводим к строке: часы уйдут ему, а не
            # этому станку. Свой номер игнорируем — это не перевод.
            other = ev.get("other_machine") or ev.get("machine")
            if other is not None:
                other = str(other).strip() or None
                if other == str(m.get("machine") or "").strip():
                    other = None
            ev["other_machine"] = other
        m["events"] = events
    data["machines"] = machines
    return data


def extract_structured(text: str,
                       images: Optional[List[Image]] = None,
                       progress: Optional[Callable[[str], None]] = None
                       ) -> Dict[str, Any]:
    """Отправить переписку (и фото) в ИИ и вернуть структуру по станкам.

    По умолчанию (AI_PER_MACHINE=true) разбор идёт ПО ОДНОМУ СТАНКУ ЗА ВЫЗОВ:
    сначала номера станков находятся в тексте без ИИ, затем на каждый делается
    свой запрос со всей перепиской. Так модель не теряет станки и часы. Если
    станки в тексте не нашлись — работает старый режим «весь день одним
    запросом».

    progress — куда сообщать, на чём сейчас разбор (см. webapp/jobs.py): станок
    за станком по одному запросу, и без этих сообщений минутная сборка на
    странице выглядит зависшей.

    Бросает AIExtractError при проблемах с сетью, доступом или разбором.
    """
    s = _settings()
    _check_ready(s)
    if getattr(s, "ai_per_machine", True):
        machines = detect_machines(text)
        if machines:
            return extract_structured_per_machine(text, images, machines,
                                                  progress=progress)
        logger.warning("Номера станков в тексте не найдены — разбираю весь "
                       "день одним запросом")
    if progress:
        progress("станки в переписке не нашлись — разбираю весь день одним "
                 "запросом")
    return _extract_once(text, images)


def _check_ready(s) -> None:
    if not s.ai_enabled:
        raise AIExtractError("ИИ выключен (AI_ENABLED=false)")
    if not s.ai_api_key:
        raise AIExtractError("Не задан AI_API_KEY")


# Шапка сообщения из day_text(): «--- сообщение 5, обсуждение по станку №91 …».
_SECTION_HEAD_RE = re.compile(r"обсуждение по станку №(\d+[а-яё]*)")


def detect_machines(text: str) -> List[str]:
    """Номера станков в переписке — без ИИ, по справочнику норм.

    Тот же сканер, что отвечает «данные приняты, вижу станок такой-то»
    (services/shift_store.scan_text): берутся только номера из справочника,
    поэтому «303 из 303» станком не станет.

    ШАПКА СООБЩЕНИЯ надёжнее справочника: файл смены раскладывается по станкам
    ещё до ИИ, и номер в шапке взят из заголовка темы («91 машина(плановый пуск
    23.09.2026г.)»). Номера нет в справочнике норм — и станок молча исчезал из
    отчёта целиком (прогон 21.09 и 22.09.2026: №91 был в переписке, в отчёт
    не попал ни одной строкой). Такие станки всё равно считаются как «нет
    нормы» — честнее потерянного станка.
    """
    try:
        from .shift_store import scan_text
    except Exception:                                   # pragma: no cover
        return []
    out = list(scan_text(text or "").machines)
    for num in _SECTION_HEAD_RE.findall(text or ""):
        if num not in out:
            out.append(num)
    return out


def _extract_once(text: str, images: Optional[List[Image]] = None,
                  instruction: Optional[str] = None,
                  progress: Optional[Callable[[str], None]] = None
                  ) -> Dict[str, Any]:
    """Один запрос к ИИ с повтором при обрыве потока."""
    s = _settings()
    _check_ready(s)
    images = images or []
    fmt = s.ai_api_format.strip().lower()
    call = _call_openai if fmt == "openai" else _call_anthropic

    # Повтор при обрыве потока. Рассуждающая модель через шлюз иногда закрывает
    # соединение после «мыслей», не отдав ответ (см. AIRetryableError). Тот же
    # запрос при повторе почти всегда проходит, поэтому пробуем несколько раз.
    attempts = max(1, int(getattr(s, "ai_retries", 2)) + 1)
    last_err: Optional[AIRetryableError] = None
    for i in range(attempts):
        logger.info("ИИ-разбор: формат=%s, модель=%s, фото=%d (попытка %d/%d)",
                    fmt, s.ai_model, len(images), i + 1, attempts)
        if progress:
            progress(f"ждём ответ ИИ (модель {s.ai_model}"
                     + (f", попытка {i + 1} из {attempts}" if attempts > 1
                        else "") + ")")
        try:
            raw = call(text, images, instruction)
        except AIRetryableError as e:
            last_err = e
            if i + 1 < attempts:
                logger.warning("Повтор запроса к ИИ (%d/%d): %s",
                               i + 1, attempts, e)
                time.sleep(2 * (i + 1))
                continue
            raise
        return _normalize(_extract_json(raw))
    # сюда не доходим: последняя попытка либо вернула, либо бросила
    raise last_err or AIExtractError("ИИ не дал ответа")


def extract_structured_per_machine(text: str,
                                   images: Optional[List[Image]] = None,
                                   machines: Optional[List[str]] = None,
                                   progress: Optional[Callable[[str], None]]
                                   = None
                                   ) -> Dict[str, Any]:
    """Разбор ПО ОДНОМУ СТАНКУ ЗА ВЫЗОВ и сборка одной структуры дня.

    Решение пользователя (28.08.2026): «давай тогда проверим, чтобы каждый
    станок шёл запросом к ИИ». Один запрос на станок дороже и дольше, но модель
    перестаёт терять станки, операторов и часы, как это было при разборе всего
    дня одним запросом.

    Если по какому-то станку запрос упал — остальные станки всё равно попадут
    в отчёт, а по упавшему появится предупреждение в warnings.
    """
    machines = machines or detect_machines(text)
    if not machines:
        return _extract_once(text, images, progress=progress)
    out: Dict[str, Any] = {"date": None, "machines": [], "warnings": []}
    total = len(machines)
    for index, num in enumerate(machines, start=1):
        instruction = PER_MACHINE_INSTRUCTION.format(machine=num)
        logger.info("ИИ-разбор станка №%s (%d станков всего)",
                    num, total)
        if progress:
            progress(f"станок №{num} — {index} из {total}")
        got = 0
        for attempt in (1, 2, 3):
            if attempt > 1:
                # Перед переспросом ждём. Отказ шлюза живёт секунды, а три
                # попытки без паузы уходят за десятые доли и промахиваются:
                # 21.09.2026 ст.98 отвалилась именно так (502 + два обрыва),
                # и весь 35-минутный прогон вышел без данных по станку.
                pause = MACHINE_RETRY_PAUSE_S * (attempt - 1)
                if progress:
                    progress(f"станок №{num} ({index} из {total}) — переспрашиваю, "
                             f"попытка {attempt} из 3 (ждём {int(pause)} с)")
                time.sleep(pause)
            try:
                part = _extract_once(text, images, instruction,
                                     progress=progress)
            except AIExtractError as e:
                logger.error("Станок №%s не разобран (попытка %d): %s",
                             num, attempt, e)
                if attempt == 3:
                    out["warnings"].append(f"станок №{num}: {e}")
                continue
            if not out.get("date") and part.get("date"):
                out["date"] = part["date"]
            events = 0
            for machine in part.get("machines") or []:
                # Модель могла вернуть заодно и другие станки — берём только тот,
                # о котором спрашивали, иначе станки задвоятся между вызовами.
                if str(machine.get("machine") or "").strip() and \
                        not _same_machine(machine.get("machine"), num):
                    continue
                machine["machine"] = num
                out["machines"].append(machine)
                events += len(machine.get("events") or [])
                got += 1
            if got:
                if progress:
                    progress(f"станок №{num} разобран: событий {events} "
                             f"({index} из {total})")
                break
            # Пустой ответ без ошибки — станок молча пропал бы из отчёта и в
            # Excel выглядел бы как «нет данных» (прогон (8): так исчез ст.98,
            # прогон 31.08 — ст.111). Спрашиваем ещё раз (всего до трёх раз) и
            # только потом сдаёмся с предупреждением.
            logger.warning("Станок №%s: ИИ вернул пустой разбор (попытка %d)",
                           num, attempt)
        if not got:
            out.setdefault("not_parsed", []).append(str(num))
            msg = (f"станок №{num}: ИИ не вернул данных, хотя станок есть в "
                   f"переписке — цифры по нему в отчёт не попали")
            if _looks_like_has_numbers(text, num):
                msg += ("; в переписке по нему есть показания счётчика — "
                        "отчёт неполный, запустите его повторно")
            if msg not in out["warnings"]:
                out["warnings"].append(msg)
    if not out["machines"]:
        raise AIExtractError(
            "ИИ не дал данных ни по одному станку"
            + (": " + "; ".join(out["warnings"]) if out["warnings"] else ""))
    return out


def _looks_like_has_numbers(text: str, num: Any) -> bool:
    """Есть ли в блоке этого станка показания счётчика (числа ≥5 цифр).

    Нужно только для силы предупреждения: если по потерянному станку в
    переписке были счётчики, отчёт без него заведомо неполный, и пользователь
    должен узнать это словами, а не по пустой строке в Excel.

    Блок станка — часть текста от упоминания его номера до упоминания
    следующего станка (мастера пишут переписку именно так: «–111 … –121 …»).
    """
    import re
    from . import machine_rates
    key = machine_rates._norm_key(num)
    if not key:
        return False
    low = (text or "").lower()
    known = set(machine_rates.known_machines())
    marks = []
    for m in re.finditer(r"(\d{2,3}\s?тр|\d{2,3})(?!\d)", low):
        found = machine_rates._norm_key(m.group(1).replace(" ", ""))
        if found in known:              # только реальные номера парка
            marks.append((m.start(), found))
    for i, (pos, found) in enumerate(marks):
        if found != key:
            continue
        end = marks[i + 1][0] if i + 1 < len(marks) else len(low)
        if re.search(r"\d{5,}", low[pos:end]):
            return True
    return False


def _same_machine(a: Any, b: Any) -> bool:
    """Один ли это станок («98» == «98 » == «№98» == «98м» == «98 машина»).

    Хвост «м»/«машина» после цифр отбрасывается: мастера пишут «111м», и при
    строгом сравнении такой ответ модели отбрасывался как «другой станок» —
    станок молча исчезал из отчёта (прогон 31.08: ст.111 с самым большим
    блоком данных ушёл в not_parsed). Буквенные номера («14тр») не трогаем.
    """
    suffixes = ("машины", "машина", "машине", "машин", "станок", "станка", "м")

    def norm(v: Any) -> str:
        s = "".join(ch for ch in str(v or "").lower()
                    if ch.isalnum())
        for suf in suffixes:
            if s.endswith(suf) and s[:-len(suf)].isdigit():
                return s[:-len(suf)]
        return s
    return norm(a) == norm(b)

