def test_bare_sch_does_not_steal_other_counters():
    """Голое «сч» внутри подписи другого показателя не создаёт показания.

    «Ср.сч» и «Ср.  сч» — это СРЕДНИЙ счётчик. Если бы «сч» засчиталось общим,
    в отчёте у 151-й стояло бы 15070 вместо 790782. Второй вариант (мастер или
    PDF ставят два пробела) буквальным маркерам не читается вообще — пусть
    средняя цифра останется вне отчёта, но не переедет в общий счётчик.
    """
    def counters(text):
        return [key for _a, _f, key in rr._counter_positions(text)]

    assert counters("Об. Сч.: 790782 Ср. Сч. 15070 из 14800") == [
        "общий_счётчик", "средний_счётчик"]
    assert counters("Конец смены Общий сч.21453550 Ср.  сч 1036 из 1360") == [
        "общий_счётчик"]
    assert counters("Ср.  сч.: 250узл. из 1400") == []
    # «расчёт» — не счётчик.
    assert counters("212 протяжных узлов, расчёт 55") == []
    assert counters("Склад 49-24.08.26 187.3 51 250.5 зел Сч 21509000 "
                    "Развито 160 шпулей") == ["общий_счётчик", "шпуля_развито"]
    print("✅ голое «сч» не перетирает средний счётчик и не ловит «расчёт»")


def test_same_file_is_not_accepted_twice():
    """Повтор того же файла в смену ничего не добавляет: отчёт не задваивается."""
    _tmp_store()
    first = ss.add_document("22.09.2026.csv", CSV.encode("utf-8"),
                            author="Руслан")
    assert not first.file_duplicate
    again = ss.add_document("22.09.2026 (1).csv", CSV.encode("utf-8"),
                            author="Руслан", caption="скинула ещё раз")
    assert again.file_duplicate and again.duplicate_of == "22.09.2026.csv"
    assert again.messages == first.messages, (again.messages, first.messages)
    assert len(ss.load_day(first.date)["messages"]) == first.messages
    # Те же самые данные, но файл пересохранён (другие байты) — тоже повтор:
    # считаем по тексту, а не по байтам.
    assert ss.add_document("chat.txt", CSV.encode("utf-8") + b"\r\n"
                           ).file_duplicate
    # Исправленный файл — ДРУГОЙ, его принимаем.
    fixed = CSV.replace("790782", "790800").encode("utf-8")
    third = ss.add_document("22.09.2026 (2).csv", fixed)
    assert not third.file_duplicate
    assert third.messages == first.messages + 7, third.messages
    # Очистка смены (/reset) снимает и запрет на повтор.
    ss.clear_day(first.date)
    assert ss.accepted_documents(first.date) == []
    assert not ss.add_document("22.09.2026.csv", CSV.encode("utf-8")).file_duplicate
    print("✅ повтор файла не множит данные, исправленный — принимается")


def test_re_upload_rereads_sections_in_place():
    """Тот же файл перечитывает разделы заново — так чинится уже принятая смена.

    Защита от повтора раньше только молчала «уже принимали»: если разбор
    выгрузки починили ПОСЛЕ того, как смену приняли, испорченные разделы
    оставались в накопителе, и убрать их можно было лишь очисткой смены и
    новым (платным) запросом к ИИ. Теперь переприсланный файл кладёт свежие
    разделы вместо своих же старых — данных не прибавляется.
    """
    _tmp_store()
    first = ss.add_document("22.09.2026.csv", CSV.encode("utf-8"),
                            author="Руслан", caption="смена за 22.09")
    assert first.messages == 8, first.messages       # подпись + семь разделов
    data = ss.load_day(first.date)
    for m in data["messages"]:
        if m["machine"] == "151":
            m["text"] += "\nЮлия Черныш, 07:01: Конец смены Общ.сч. -_125077_"
    ss._save_day(data)

    again = ss.add_document("22.09.2026 (1).csv", CSV.encode("utf-8"))
    assert again.file_duplicate and again.duplicate_of == "22.09.2026.csv"
    assert again.messages == first.messages, again.messages
    day = ss.load_day(first.date)
    stored = "\n".join(m["text"] for m in day["messages"])
    assert "125077" not in stored                    # старый хвост перечитался
    assert [d["name"] for d in ss.accepted_documents(first.date)] \
        == ["22.09.2026.csv"], ss.accepted_documents(first.date)
    # Подпись первого приёма на месте и не продублировалась.
    assert sum(1 for m in day["messages"]
               if m["text"] == "смена за 22.09") == 1
    # Номера сообщений не повторяются: из номера строится имя файла фото.
    indexes = [m["index"] for m in day["messages"]]
    assert len(set(indexes)) == len(indexes), indexes
    print("✅ повтор файла перечитывает разделы вместо старых, данных не прибавилось")


