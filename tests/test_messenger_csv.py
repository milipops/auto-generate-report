def test_topic_mirror_is_not_counted_as_own_data():
    """Копия чужой темы не лежит в разделе станка, который не работал."""
    secs = ss.split_sections(MIRROR.strip())
    by = {s.machine: s for s in secs}
    assert set(by) == {"321", "14тр"}, set(by)
    # Всё своё осталось у 321-й.
    assert "125077" in by["321"].text and "4,2 кг" in by["321"].text
    # …и ни одной копией не уехало в стоявшую 14-ю.
    assert "125077" not in by["14тр"].text, by["14тр"].text
    assert "кг" not in by["14тр"].text, by["14тр"].text
    assert by["14тр"].mirrored == 2, by["14тр"].mirrored
    # Своё сообщение темы при этом живое — раздел не опустел.
    assert "После совещания" in by["14тр"].text
    # Фантомных авторов из чужой темы у раздела нет.
    assert by["14тр"].authors == ["Юлия Черныш"], by["14тр"].authors
    print("✅ копия чужой темы не попала в раздел стоявшего станка")


