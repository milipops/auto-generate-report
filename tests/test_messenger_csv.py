def test_time_column_not_first_still_reads_the_shift():
    """Выгрузка, где «Дата и Время» стоит НЕ в первой колонке, читается весь.

    Проверка «первая клетка — время» раньше делалась до разбора колонок: в
    файле, где первым столбцом идёт «Тип», она отбрасывала ВСЕ строки смены, и
    молча — счётчик «разобралось меньше 60% строк» тут не срабатывает, потому
    что строки не считались вообще. Время теперь берётся из колонки, которую
    назвала строка заголовка.
    """
    permuted = (
        "Тип;Дата и Время сообщения;Имя автора;Текст сообщения\n"
        "Сообщение;2026-09-22 06:36:11;;151 машина(Арташина) - информация "
        "за смену 22.09.2026г. 06:36\n"
        "Ответ;2026-09-22 09:18:05;Татьяна Арташина;09:15 машина в работе. "
        "Об. Сч.: 790782 09:18\n"
        "Сообщение;2026-09-22 06:37:38;;98 машина(Белякова) - информация "
        "за смену 22.09.2026г. 06:37\n"
        "Ответ;2026-09-22 06:43:19;Белякова С.;7.00 машина в работе "
        "Сч 21509000 06:43\n")
    secs = ss.split_sections(permuted)
    machines = sorted(s.machine for s in secs if s.machine)
    assert machines == ["151", "98"], secs
    text151 = next(s.text for s in secs if s.machine == "151")
    assert "790782" in text151, text151
    text98 = next(s.text for s in secs if s.machine == "98")
    assert "21509000" in text98, text98
    print(f"✅ станки из колонок не по порядку: {machines}")


