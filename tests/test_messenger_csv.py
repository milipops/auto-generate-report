def test_no_line_is_lost_in_parsing():
    """Ни одно сообщение не пропадает: каждое слово файла осталось в секции.

    Проверка придумана не для порядка: расклейка слипшихся строк
    (split_glued_text) вставляет перевод строки и ВНУТРИ записи — «Склад
    49-24.08.26» рвался перед «08.26», принятым за время 08:26, и счётчик
    21509000 станка №98 исчезал из смены целиком.
    """
    secs = ss.split_sections(CSV.strip())
    stored = "\n".join(s.text for s in secs)
    missing = []
    for line in CSV.strip().split("\n")[1:]:
        cells = line.split(";")
        if len(cells) < 4:
            continue
        for word in (w for w in re.split(r"\s+", cells[3].strip('" '))
                     if len(w) > 6):
            if word not in stored:
                missing.append(word)
    assert not missing, missing
    assert "21509000" in stored and "49-24.08.26" in stored
    print("✅ ни одно сообщение не потерялось при разборе")


def test_export_variants_are_parsed():
    """Варианты выгрузки (табы, другая дата, без колонки «Тип») — те же станки.

    Выгрузку делают то Excel («;»), то буфером обмена из чата, и набор колонок
    с датой отличается от файла к файлу; разложить надо в любом случае.
    """
    lines = CSV.strip().split("\n")
    variants = {
        "табуляция": [l.replace(";", "\t") for l in lines],
        "дата 22.09.2026": [l.replace("2026-09-22 ", "22.09.2026 ") for l in lines],
        "без колонки Тип": [";".join(c for i, c in enumerate(l.split(";")) if i != 1)
                            for l in lines],
        "без строки заголовка": lines[1:],
    }
    want = ["121", "151", "251", "98", "91", "14тр", "15тр"]
    for name, rows in variants.items():
        got = [s.machine for s in ss.split_sections("\n".join(rows))]
        assert got == want, (name, got)
    print("✅ варианты выгрузки (табы/дата/без колонки типа) разложены верно")


def test_export_with_role_column():
    """Выгрузка с колонкой «Роль» (реальный «22.09.2026.csv») разложена по машинам.

    Между автором и текстом там стоит «Администратор», и без карты колонок
    роль приклеивалась к тексту («Администратор; 14т машина…»), заголовок темы
    не узнавался, и вся смена ложилась ОДНИМ сообщением без станка — номер
    угадывала модель, показания уезжали не на тот станок.
    """
    lines = CSV.strip().split("\n")
    rows = [lines[0].replace("Текст сообщения", "Роль;Текст сообщения")]
    for l in lines[1:]:
        cells = l.split(";")
        cells.insert(3, "Администратор" if cells[2] == "Юлия Черныш" else "")
        rows.append(";".join(cells))
    no_head = "\n".join(rows[1:])

    want = ["121", "151", "251", "98", "91", "14тр", "15тр"]
    for name, text in (("с заголовком", "\n".join(rows)), ("без заголовка", no_head)):
        secs = ss.split_sections(text)
        assert [s.machine for s in secs] == want, (name, [s.machine for s in secs])
        stored = "\n".join(s.text for s in secs)
        assert "Администратор" not in stored, (name, "роль утёрлась в текст")
    # Показания своего станка не разъехались и в этом варианте.
    by = {s.machine: s for s in ss.split_sections("\n".join(rows))}
    assert "790782" in by["151"].text and "790782" not in by["251"].text
    print("✅ выгрузка с колонкой «Роль» разложена по машинам, роль вне текста")


