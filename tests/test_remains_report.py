def test_excel_sheet_only_when_there_is_waste():
    from openpyxl import load_workbook
    day = rr.build_day_remains(
        DATE, messages=[{"text": FULL, "machine": "251"}, {"text": BLANKS}])
    with tempfile.TemporaryDirectory() as tmp:
        path = os.path.join(tmp, "with.xlsx")
        excel_export.export_shift_reports(_reports(), path, date=DATE,
                                          remains=day)
        wb = load_workbook(path)
        assert f"Остатки {DATE[:5]}" in wb.sheetnames, wb.sheetnames
        ws = wb[f"Остатки {DATE[:5]}"]
        rows = [[c.value for c in r] for r in ws.iter_rows()]
        flat = "\n".join(str(v) for r in rows for v in r if v is not None)
        assert "Камбаров" in flat, "оператор подтянулся из отчёта смены"
        assert "указать причины" not in flat, "подсказка бланка в отчёте"
        assert "21140500" in flat and "148 из 150" in flat
        assert "—" in flat, "незаполненное поле показано прочерком"
        assert any(r and r[0] and "ИТОГО" in str(r[0]) for r in rows)

