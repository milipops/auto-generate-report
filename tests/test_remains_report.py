"""Остатки сырья и сдаваемые отходы по машинам.

Просьба пользователя 09.09.2026: мастера присылают на конец смены по каждой
машине блок «Конец(начало) смены … Сдаваемые отходы», и этот учёт должен идти
отдельной страницей в Excel и попадать в выгрузку для 1С.

Разбор блока делает НЕ ИИ, а регулярки (`services/remains_report.py`): шаблон
жёсткий, вызов ИИ на смену остаётся один и только про структуру работы.
Поэтому тест держит именно разбор и то, во что он превращается:

* полный бланк читается целиком: показания «148 из 150» и все шесть видов
  отходов;
* пустое поле — это НЕ ноль: незаполненное остаётся None и печатается «—»,
  а присланный «0» так и остаётся нулём;
* подсказка пустого бланка «(указать причины появления)» причиной не считается
  ни из скобок, ни из хвоста строки;
* большое показание счётчика не превращается в «2,11405e+07»;
* два сообщения по одному станку сливаются, последнее слово за мастером;
* блок без номера станка не теряется и даёт предупреждение;
* итоги по видам и общий вес считаются по факту;
* в Excel лист «Остатки» появляется только когда отходы есть, оператор
  подтягивается из отчёта смены, а нулевые станки парка в напоминание
  «не присылали» не попадают;
* в выгрузке 1С колонки отходов дописаны В КОНЕЦ (сопоставление первых колонок
  у пользователя уже настроено), а в JSON есть блок по станку и итог за смену;
* вес единицы сырья («бобины по 0,925кг») и границы диапазона («от 3,8кг до
  4,2 кг», «весом(от 550-700)») отходами не становятся;
* окно простоя («Подмена 16.00-16.55») не становится показанием «подмена 16»;
* срез, записанный числом ПЕРЕД подписью («1 Ср из 4»), читается, и в одном
  замере берётся последний; узлы («Срез 950 уз. из 1600 уз.») идут в средний
  счётчик, а не в колонку «срезы»;
* замер принадлежит станку ИЗ ШАПКИ РАЗДЕЛА выгрузки («–251»): номер чужой
  машины внутри замера («16:54 подмена на 151,251 в работе») показаний не
  переводит на чужой станок — так же и сданные килограммы остаются в своём
  разделе, а не уезжают по подсказке темы;
* вид отходов, названный именительным падежом с большой буквы («Развивка 3х
  шпуль окончена Вес 2,8кг»), считается; строчная форма в описании работы —
  нет, иначе одна сдача ложится двумя видами;
* вес из примера записи журнала («произвести запись например ( … вес 0.12 кг)»)
  и паспортный вес бобины в скобках («маленькие (1,400 кг)») вопросы не вызывают;
* «10, 4кг» — это 10,4 кг с пробелом после запятой из выгрузки, а не «4».

Запуск: python3 tests/test_remains_report.py (или через tests/_run_all.py).
"""
