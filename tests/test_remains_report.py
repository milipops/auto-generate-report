def _block(text, hint=None):
    blocks = rr.parse_blocks(text, machine_hint=hint)
    assert len(blocks) == 1, f"ожидался один блок, вышло {len(blocks)}"
    return blocks[0]


def test_full_template_read_completely():
    b = _block(FULL, hint="251")
    assert b.machine == "251"
    assert b.moment == "конец"
    assert b.counter("общий_счётчик") == 21140500
    assert b.counters["средний_счётчик"] == (148, 150)
    assert b.counter_text("средний_счётчик") == "148 из 150"
    assert b.waste == {"навивка_шпулей": 3.5, "развивка_шпулей": 1.2,
                       "наладочные": 0, "протяжка_узлов": 2,
                       "подмена_шпулярника": 0.8, "прочие": 1.5}, b.waste
    assert b.waste_total == 9.0, b.waste_total
    assert "масло" in (b.state or "")


def test_empty_field_is_not_zero():
    b = _block(BLANKS)
    assert b.machine == "321"
    assert b.waste["наладочные"] == 4
    assert b.waste["навивка_шпулей"] is None, "прочерк — это не ноль"
    assert b.waste["прочие"] is None
    # Незаполненное показание в блок вообще не кладём — читается как «—».
    assert b.counter("средний_счётчик") is None
    assert b.counter_text("средний_счётчик") == "—", "прочерк, а не 0"
    # А присланный руками ноль остаётся нулём.
    zero = _block(FULL, hint="251")
    assert zero.waste["наладочные"] == 0
    assert zero.waste["наладочные"] is not None


def test_blank_form_hint_is_not_a_reason():
    assert _block(BLANKS).other_reason == ""
    assert _block(FULL, hint="251").other_reason == "обрыв нити при заправке"
    for tail in ("Прочие(указать причины появления) - ____кг.",
                 "Прочие (указать причины) - 2 кг",
                 "Прочие - ___кг"):
        # Наладочные нужны, чтобы блок вообще состоялся: строка из одних
        # прочерков сама по себе отходами не считается.
        b = _block("Сдаваемые отходы машина 251:\nНаладочные - 1кг\n" + tail)
        assert b.other_reason == "", (tail, b.other_reason)


