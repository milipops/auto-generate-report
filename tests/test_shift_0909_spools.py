"""Правило пользователя от 09.09.2026 про сход шпуль.

«Так же при сходе шпулей машина ставится в стоп, как было многократно на 321
машине».

До этого правила «Стоп. Сошло 8 шпулей. Подставляю.» уходило в «прочее» либо, из
за слова «шпул», в «навивку/намотку шпулей» — а та считается работой ПАРАЛЛЕЛЬНО
работающей машине. Простой станка при этом исчезал, хотя мастер прямо пишет
«стоп». На ст.321 за 08.09.2026 таких записей больше двадцати за смену.

Проверять надо и обратное: корень «сошл» есть в «часы сошлись», и сходом это
считать нельзя. Поэтому рядом требуется слово «шпул» (гейт _SPOOL_STOP_RE).
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from services.shift_report import (classify_stop, machine_stopped_for,
                                   STRETCH_LABEL)

SPOOL_LABEL = "замена шпуль (станок стоит)"

# Сход/подстановка шпулей теперь называется ДОТЯГИВАНИЕМ — так эта строка
# стоит в отчёте пользователя почти каждый день с 19.08 по 14.09 (эталон 14.09,
# ст.321: «6,95 | дотягивание (подстановка сошедших шпулей)»). Правило от
# 09.09.2026 при этом не изменилось: станок стоит, и это простой, а оператор
# в это время работает. Смена только названия строки.


def test_spool_off_is_a_machine_stop():
    """Сход шпуль — простой станка, как его пишет мастер 321-й."""
    for text in ("Машина стоп. Сошло 2 шпули. Меняю.",
                 "Машина стоп. Сошло 3 шпули.",
                 "Стоп. Сошла 1 шпуля. Подставляю.",
                 "Стоп . Визуально сошло 6 шпулей.",
                 "Стоп.Сошло 8 шпулейСрезовой 656 из 750",
                 "Машина стоп. Сошло 11 шпулей. Подставляю.",
                 "Машина стоп. Сч. 118355.Сошли 2 шпули. Меняю."):
        label, worked = classify_stop(text)
        assert label == STRETCH_LABEL, (text, label)
        assert worked, "оператор в это время работает — он меняет шпули"
        assert machine_stopped_for(text, label), f"станок должен стоять: {text}"
    print(f"✅ сход шпуль = простой станка: {STRETCH_LABEL}")


def test_putting_spools_back_is_the_same_stop():
    """Подстановка шпуль — вторая половина того же простоя, не работа.

    Слово «подстановка» входит в само название категории дотягивания, поэтому
    оно и даёт её — это одно и то же дело, что сход шпули.
    """
    label, _worked = classify_stop("Подставляю 8 шпулей")
    assert label == STRETCH_LABEL, label
    assert machine_stopped_for("Подставляю 8 шпулей", label)
    print("✅ подстановка шпуль тоже простой (дотягивание)")


def test_hours_added_up_is_not_a_spool_off():
    """«Часы сошлись» — не сход шпуль: корень «сошл» без слова «шпул»."""
    for text in ("часы сошлись к норме 11,25",
                 "данные по смене не сошлись с журналом"):
        label, _worked = classify_stop(text)
        assert label != SPOOL_LABEL, (text, label)
    print("✅ «часы сошлись» сходом шпуль не считается")


def test_winding_spools_stays_parallel_work():
    """Навивка шпулей без «стоп»/«сошло» — по-прежнему работа параллельно."""
    label, worked = classify_stop("навивка шпулей на 251")
    assert label == "навивка/намотка шпулей", label
    assert worked
    print("✅ навивка шпулей осталась параллельной работой")


def test_spool_change_wording_still_works():
    """Прежние формулировки замены шпуль не сломались.

    Замена БЕЗ слова «сошл»/«сошедш» — это другая операция (поставить свежие
    шпули, а не вернуть сошедшие), поэтому категория остаётся прежней.
    """
    for text in ("замена шпуль", "меняю шпули", "поменял шпули на станке"):
        label, _worked = classify_stop(text)
        assert label == SPOOL_LABEL, (text, label)
    print("✅ старые формулировки замены шпуль читаются как раньше")


def test_naladka_of_spool_sensor_is_not_stretching():
    """Наладка датчика схода шпули — это НАЛАДКА, а не дотягивание.

    Эталон 21.08: «Пронкин — наладка датчика схода шпули, продувка узла
    пылесосом (08:52-09:20)» стоит в привлекаемом персонале и в простоях как
    наладка. Слово «сход» в такой записи описывает предмет наладки, а не работу
    оператора по подстановке шпулей.
    """
    text = "приёмка наладки датчика схода шпули с наладчиком Пронкиным"
    label, _worked = classify_stop(text)
    assert label == "наладка/переналадка", (text, label)
    print("✅ наладка датчика схода осталась наладкой")


if __name__ == "__main__":
    test_spool_off_is_a_machine_stop()
    test_putting_spools_back_is_the_same_stop()
    test_naladka_of_spool_sensor_is_not_stretching()
    test_hours_added_up_is_not_a_spool_off()
    test_winding_spools_stays_parallel_work()
    test_spool_change_wording_still_works()
