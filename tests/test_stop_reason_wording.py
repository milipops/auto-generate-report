# ─────────────── 6. пуск машины против выпущенных ниток ───────────────

def _naladka_day(reason: str):
    return _one({"machine": "121", "operator": "Белякова",
                 "operator_shift_end": "19:00",
                 "events": [{"kind": "наладка", "reason": reason}]})


def test_thread_release_does_not_cancel_all_shift_naladka():
    """«Выпустил нитки» — работа, а не пуск: день остаётся в наладке."""
    r = _naladka_day("машина в стопе, в очереди на наладку весь день; "
                     "за смену выпустила нитки со стороны шпулей")
    assert r.naladka_all_shift is True, r.naladka_all_shift
    print("✅ «выпустил нитки» наладку весь день не отменяет")


def test_real_resume_still_cancels_all_shift_naladka():
    """А настоящий пуск («машину пустили») по-прежнему отменяет признак."""
    r = _naladka_day("машина в стопе, нужна наладка; в 15:00 машину пустили")
    assert r.naladka_all_shift is False, r.naladka_all_shift
    print("✅ пуск машины наладку весь день отменяет")


# ─────────────── 7. сход шпуль: сокращение и перечень номеров ───────────────

def test_spool_abbreviation_is_the_same_spool():
    """«сошли 4 и 5 шп.» — тот же сход шпуль, что «сошли 4 шпули».

    На ст.321 за 24.09.2026 мастер пишет одно и то же двумя способами, и
    сокращение «шп» не узнавалось ни сходом, ни заменой шпуль: 8 одинаковых
    записей падали в «прочее» (где оператор занят), а их часы молча переезжали
    в надуманное «отсутствие оператора» (1,17 ч).
    """
    for text in ("сошли 4 и 5 шп. Ср. сч. 524", "сошла 28 шп Ср. сч. 608",
                 "сошла 33 шп. Ср. сч. 619", "сошли 16 , 17 и 18 шп. Ср. сч. 581"):
        label, _active = classify_stop(text)
        assert label == STRETCH_LABEL, (text, label)
        assert machine_stopped_for(text, label) is True, text
    print("✅ «шп.» — та же шпуля: сход назван дотягиванием")


def test_spool_number_list_is_not_winding():
    """Перечень сошедших номеров не разрывает сход — это не навивка.

    Между «сошли» и «шпули» встаёт весь список (32 символа), прежнее окно
    связки в 30 символов разрывалось, и 1,12 ч простоя уезжали в параллельную
    навивку при «работающей» машине (ст.321 за 24.09.2026).
    """
    text = "сошли 41,42,43,45,46,47,48, 49,50,51 шпули. Ср. сч:639 из 760"
    label, _active = classify_stop(text)
    assert label == STRETCH_LABEL, label
    assert label != WINDING_LABEL, label
    assert machine_stopped_for(text, label) is True, text
    print("✅ длинный перечень номеров остался сходом шпуль")


def test_spooler_word_does_not_hijack_a_named_reason():
    """Слово «шпулярник» не перекрывает названную операцию.

    «обрыв нити со шпулярника, устранил наладчик Пронкин» (ст.111 за
    24.09.2026, 6 записей) получало параллельный ярлык «замена шпулярника /
    переход на ассортимент» — из-за корня «шпул» внутри слова «шпулярник».
    Имя строки неверно (никто шпулярник не менял), и часы считались при идущей
    машине, хотя станок стоял и работала служба наладки.
    """
    for text in ("обрыв нити со шпулярника, устранил наладчик Пронкин",
                 "стоп, обрыв нити со шпулярника, устранил наладчик"):
        label, _active = classify_stop(text)
        assert label == NALADKA_LABEL, (text, label)
    # Переход на ассортимент — он и есть параллельная работа, без изменений.
    assert classify_stop("переход на др. ассортимент")[0] == ASSORT_LABEL
    # Замечание о весе со шпулярника — не замена шпулярника (правило 03.09).
    assert classify_stop("Вес начинки со шпулярника большая")[0] != ASSORT_LABEL
    print("✅ «шпулярник» не подменяет наладку и не выдумывает замену")


def test_spool_off_without_spool_word_is_not_a_stop():
    """Обратная проверка: «часы сошлись» — не сход шпуль."""
    for text in ("часы сошлись", "данные не сошлись, сверяю журнал"):
        label, _active = classify_stop(text)
        assert label != STRETCH_LABEL, (text, label)
    print("✅ «сошлись» сходом шпуль не считается")


PAPER_LABEL = "документация и культура производства"


def test_paperwork_is_named_not_misc():
    """Бумага и 5С — названное дело, а не «прочее»."""
    for text in ("заполнение журнала, сопроводительных листов, бирок",
                 "культура производства", "заполнение журнала, чата"):
        label, _active = classify_stop(text)
        assert label == PAPER_LABEL, (text, label)
    # Обратная проверка: названная операция сильнее бумаги.
    assert classify_stop("чинка, по пути заполнила журнал")[0] == "чинка/ремонт"
    print(f"✅ бумага названа: {PAPER_LABEL}")


def test_stop_until_a_date_is_written_in_master_words():
    """«Машина в стопе до 15.10.2026 г.» — стоп на срок, словами мастера."""
    label, active = classify_stop("машина в стопе до 15.10.2026 г.")
    assert label.startswith("машина в стопе до 15.10"), label
    assert label != "прочее", label
    # Станок в долгосрочном стопе — у машины никого: это статус, а не операция
    # оператора, иначе смена стоящего станка стала бы его «работой».
    assert active is False, label
    # Короткая запись остаётся дословной, длинная — обрезается по фразе.
    long_text = ("машина в стопе до 15.10.2026 г.; убрана по распоряжению "
                 "начальника участка, об.сч 118526")
    label2, _a2 = classify_stop(long_text)
    assert label2 == "машина в стопе до 15.10.2026 г", label2
    # Обычная останов-запись без срока в словах мастера не уезжает: она и есть
    # «прочее» (причина не названа), и правило её не выдумывает.
    assert classify_stop("заполнение журнала")[0] == PAPER_LABEL
    print("✅ стоп до даты подписан словами мастера")


TOPIC_15TR = ("Погодина Л., 19:52: 15т машина(в стопе до 15.10.2026 г.) "
              "- информация за смену 27.09.2026г.\n"
              "Юлия Черныш, 20:29: v")


def test_stop_until_date_survives_an_empty_parse():
    """27.09 ст.15тр: в теме ОДИН заголовок и ни одного события — смена закрыта.

    Модель вернула по этому станку пустой разбор (ни счётчика, ни остановок), и
    в бланке стояли две пустые клетки, хотя мастер в заголовке темы написал срок
    простоя. Фразу «в стопе до <дата>» читаем из переписки станка, а службу не
    приписываем: в 15тр её нет (в 14тр рядом написано «инж. служба» — и там
    служба стоит).
    """
    r = _one({"machine": "15тр", "section_text": TOPIC_15TR,
              "lines": [], "events": []})
    hours, reason = _stops_columns(r)
    assert hours == 11.25, (hours, reason)
    assert reason == "машина в стопе до 15.10.2026 г", reason
    assert r.work_hours == 0.0, r.work_hours
    # Стоящий станок без фамилии: человека это работой не делает.
    assert r.operator_hours == 0.0, r.operator_work_by_reason()
    assert len(r.downtime_by_reason()) == 1, r.downtime_by_reason()
    print("✅ заголовок темы «в стопе до даты» закрыл смену станка")


def test_station_with_work_keeps_the_stop_phrase_out():
    """Обратная проверка: у станка с делом заголовок темы простой не закрывает."""
    r = _one({"machine": "15тр", "operator": "Иванова",
              "section_text": TOPIC_15TR,
              "lines": [{"assortment": "днпа 187х3", "counter_start": 100000,
                         "counter_end": 101200}],
              "events": [{"start": "08:00", "end": "09:00", "kind": "работа",
                          "reason": "навивка шпулей", "performer": None,
                          "other_machine": None}]})
    assert r.work_hours > 0.0, r.work_hours
    assert not any("стопе до" in (s.reason or "") for s in r.tech_stops), \
        [(s.hours, s.reason) for s in r.tech_stops]
    print("✅ фраза из заголовка не лезет в станок с работой")


