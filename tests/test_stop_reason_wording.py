"""Аудит правил: причины простоя по словам мастеров (правка 25.09.2026).

Правило пользователя №5 из HANDOFF: «причины простоя — словами мастеров,
дословно». Код разбирает эти слова маркерами, и пока причина не названа, часы
уходят в безликую «прочее». Дальше включается вторичное правило: у «прочего»
оператор считается занятым (operator_active=True), а станок на нераспознанном
маркере мог как стоять, так и не стоять. То есть одна ПРОПУЩЕННАЯ ФОРМУЛИРОВКА
портит не только название строки, но и часы человека, и баланс станка.

Что закрыто этим файлом (каждый случай — реальная формулировка из переписки
участка, а не выдуманная):

1. «перекур» — перерыв. Маркеры знали только «обед»/«перерыв», и 15 минут
   перекура считались РАБОТОЙ оператора при стоящем станке.
2. «ждём нитки», «нет нити/ниток» — ожидание. Категория ожидания существовала,
   но её маркеры («жду», «нет сырь») не покрывали ни одну живую форму про нити.
3. «нет питания», «цех встал» — внешние причины (то же: категория была,
   формулировки — нет).
4. «наладчик ушёл» — это ушла СЛУЖБА, а не оператор. Слово «ушёл» стоит в
   первой категории таблицы и перекрывало строку наладки.
5. «сняли вал / поставили вал» — своя причина, а не «прочее» (ст.91 за
   24.09.2026 в Excel: «0,25 | прочее»).
6. «выпустил нитки» не отменяет «станок весь день в наладке»: маркер пуска
   искался подстрокой и ловил приставку «вы-».
7. «сошли 4 и 5 шп.» — сокращение «шп» опознаётся как шпуля. Половина записей
   ст.321 за 24.09.2026 была написана именно так и падала в «прочее».
8. Перечисление сошедших номеров («сошли 41,42,...51 шпули») не разрывает
   связку глагол+шпуля и не уезжает в параллельную навивку.
9. Слово «шпулярник» не перекрывает названную операцию: навивка стоит
   последним маркером таблицы, и «обрыв нити со шпулярника, устранил
   наладчик» остаётся наладкой, а не «заменой шпулярника».
10. Бумага и порядок на участке названы мастером: «заполнение журнала,
    сопроводительных листов, бирок», «культура производства» (ст.111 за
    24.09.2026 — 0,67 ч висели в безликом «прочее»).
11. Станок, убранный в стоп до даты («машина в стопе до 15.10.2026 г.»,
    ст.15тр за 24.09.2026), подписан словами мастера, а не «прочее» на
    11,25 ч.

Обратные проверки важны не меньше: «оператор ушёл на подмену» обязано остаться
отсутствием оператора, а «часы сошлись» — не сходом шпуль.
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from services.shift_report import (                    # noqa: E402
    SHAFT_LABEL,
    STRETCH_LABEL,
    WINDING_LABEL,
    build_shift_reports_from_structured,
    classify_stop,
    is_lunch_label,
    machine_stopped_for,
)
from services.excel_export import _stops_columns                     # noqa: E402

WAIT_LABEL = "ожидание (задание, наладчик, сырьё)"
EXTERNAL_LABEL = "внешние причины"
ABSENCE_LABEL = "отсутствие оператора"
NALADKA_LABEL = "наладка/переналадка"
ASSORT_LABEL = "замена шпулярника / переход на ассортимент"


def _one(machine):
    return build_shift_reports_from_structured({"machines": [machine]})[0]


# ─────────────── 1. перекур ───────────────

def test_break_word_is_a_break():
    """«Перекур» — перерыв: станок стоит, и оператора в это время нет."""
    for text in ("перекур", "12:00-12:45 перекур", "перекур 15 минут"):
        label, active = classify_stop(text)
        assert label == "перерыв", (text, label)
        assert active is False, text
        assert is_lunch_label(label), label
        assert machine_stopped_for(text, label), text
    print("✅ перекур — перерыв, а не работа оператора")


def test_break_as_time_mark_is_not_a_break():
    """«После перекура машина в работе» — отметка времени, а не перерыв."""
    label, _active = classify_stop("после перекура машина в работе, "
                                   "продолжаю навивку шпулей")
    assert label != "перерыв", label
    assert machine_stopped_for("после перекура машина в работе", label) is False
    print("✅ «после перекура» перерывом не считается")


# ─────────────── 2. ожидание ниток ───────────────

def test_waiting_for_threads_is_waiting():
    """Ждём материал — это ожидание: оператор свободен, станок стоит."""
    for text in ("ждём нитки", "ждем нитки", "нет нити", "нет ниток",
                 "ждем замену ниток", "ожидание ниток с распределителя"):
        label, active = classify_stop(text)
        assert label == WAIT_LABEL, (text, label)
        assert active is False, text
        assert machine_stopped_for(text, label), text
    print("✅ ожидание ниток подписано ожиданием")


def test_between_is_not_waiting():
    """Короткий маркер «жду» ищет с начала слова: «между» — не ожидание."""
    label, _active = classify_stop("отогнуло водилки между 2 и 3 полотном")
    assert label != WAIT_LABEL, label
    print("✅ «между» ожиданием не считается")


# ─────────────── 3. внешние причины ───────────────

def test_power_and_shop_down_are_external():
    """Нет питания и вставший цех — причина внешняя, оператора час не работу."""
    for text in ("нет питания", "отключили свет в цеху", "цех встал"):
        label, active = classify_stop(text)
        assert label == EXTERNAL_LABEL, (text, label)
        assert active is False, text
        assert machine_stopped_for(text, label), text
    print("✅ отключение питания и цеха — внешние причины")


# ─────────────── 4. ушёл оператор против ушедшей службы ───────────────

def test_service_person_leaving_is_not_operator_absence():
    """Ушла СЛУЖБА, а не оператор — и оператор при машине остаётся.

    Живые формулировки: «наладчик ушёл», «служба наладки вытащила шнур,
    который ушёл за вал» (там «ушёл» про шнур). Слово «ушёл» стоит в первой
    категории таблицы и перекрывало и наладку, и внешнюю причину.
    """
    for text, want in (("наладчик ушёл", NALADKA_LABEL),
                       ("служба наладки вытащила шнур, который ушёл за вал",
                        NALADKA_LABEL),
                       ("электрик ушёл", EXTERNAL_LABEL),
                       ("наладчик ушёл, ждём дальше", WAIT_LABEL)):
        label, _active = classify_stop(text)
        assert label == want, (text, label)
    print("✅ уход службы не стал отсутствием оператора")


def test_operator_leaving_still_is_absence():
    """Живые формулировки отсутствия из переписки остались отсутствием."""
    for text in ("машина в стоп, оператор ушёл на подмену",
                 "машина остановлена, ушёл на подмену на 321",
                 "ушёл на подмену шпулярника на 251",
                 "отсутствие оператора", "прогул"):
        label, _active = classify_stop(text)
        assert label == ABSENCE_LABEL, (text, label)
    print("✅ оператор ушёл — по-прежнему отсутствие")


# ─────────────── 5. валы ───────────────

def test_shaft_operations_are_named():
    """Снятие/установка валов — станок стоит и причина названа словами."""
