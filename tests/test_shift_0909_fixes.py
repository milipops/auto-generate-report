def test_weight_without_kg_is_pulling_waste():
    """«Вес срезанных узлов-0,525» — это «От протяжки узлов на машине»."""
    text = ("Машина 151.\n9:05-9:17- срез полотна, замена телег.\n"
            "Вес срезанных узлов - 0,525\n9:38 - останов машины.")
    blocks = rr.parse_blocks(text, machine_hint="151")
    assert blocks, "блок не собрался"
    b = blocks[0]
    assert b.waste.get("протяжка_узлов") == 0.525, b.waste
    print("✅ «Вес срезанных узлов» без слова «кг» учтён как протяжка")


def test_glued_weight_is_not_guessed():
    """«…узлов-0,5259:38…» (экспорт склеил строки) — килограммы не берём."""
    text = "Машина в работеВес срезанных узлов-0,5259:38- останов машины."
    assert not rr._WEIGHT_RE.search(text), "склеенное время 9:38 приняли за кг"
    print("✅ склейка «0,5259:38» килограммами не считается")


