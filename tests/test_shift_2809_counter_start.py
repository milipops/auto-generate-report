# -*- coding: utf-8 -*-
"""Начало смены 28.09.2026 по №98: утренняя передача — ВЧЕРАШНЯЯ пара показаний.

Владелец: «вот показатели начальные ср сч бот не видит их по 98 машине».

Утром 28.09 мастер передал состояние станка вчерашней смены двумя числами
(«Общ. Сч 21563900» и «Сч 21574050» — ровно начало и конец 27.09), и платный
разбор поставил началом 21563900. Выпуск получился 21200 узлов = 20 ч работы
при 12-часовой смене, в Excel — «работа машины 19,63 ч из 12 часов» и
«!!! РАСХОЖДЕНИЕ: станок +9,13 ч сверх 12 ч».

Сама Елистратова начало своей смены назвала: «7.00 начало работы … Ср.сч.
21574050». Метка «Ср.сч.» — это срезовой счётчик, общим числом он не читается,
поэтому показания ОПЕРАТОРА в теме не осталось и прежнее лечение (границу
смены брать у первого показания оператора) промахивалось.

Правило: если начало темы физически не может быть состоянием перед сменой
(выпуск от него больше наработки станка за смену), началом становится самое
РАННЕЕ показание этой же темы, от которого выпуск влезает в смену. Число не
выдумывается — оно записано в переписке, и оно совпадает с конечным показанием
прошлой смены в журнале (21574050).

Обратный случай закрывает тест про 21.09.2026 (тот же станок): там первое
показание оператора есть, и граница берётся именно оно — новый путь не должен
его перебить.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from services import counter_check as cc                         # noqa: E402

# Настоящая тема №98 из выгрузки 28.09.2026 (сокращена до показаний: лишние
# слова про навивку на границу смены не влияют).
SEC_98 = """98 машина(Елистратова В) - информация за смену 28.09.2026г.
Погодина Л., 06:56: Общ. Сч 21563900 Ср сч. 1450Уз из 1450уз 1 Ср. Из 4 срезов [медиа]
Погодина Л., 06:56: Сч 21574050 1450 уз. Из 1450 4 со. Из 4
Валентина Елистратова, 07:37: 7.00 начало работы 187×3-51-250,5 зел. Склад 49-24.08.26 Ср.сч. 21574050 Подмена с 7.00 до 7.40
Валентина Елистратова, 09:43: Развито и навито 250 шп. Подмена с 13.05 до 13.55 Общ.сч 21585100 8 срезов Ср.сч. 900 узл. из 1450 узл. 19.00 конец смены.
"""

# 27.09.2026, та же 98-я: начало 21563900 → конец 21574050 (журнал станка).
PREV_END = 21574050


def test_вчерашняя_пара_не_становится_началом_смены():
    start, end, notes = cc.check_counters(
        "98", 21563900, 21585100, text=SEC_98, prev_end=PREV_END,
        prev_is_adjacent=True, operator="Елистратова")
    assert int(start) == 21574050, (start, end, notes)
    assert int(end) - int(start) == 11050, (start, end, notes)
    assert any("вчерашнее" in n for n in notes), notes


def test_выпуск_из_темы_не_лезет_в_смену_и_часы_станка_toже():
    """Собранный отчёт: 11050 узлов = 10,23 ч работы, а не 19,63 ч."""
    from services import shift_report

    machine = {
        "machine": "98", "operator": "Елистратова", "date": "28.09.2026",
        "cuts": 8, "section_text": SEC_98,
        "lines": [{"assortment": "187×3-51-250,5 зел", "client": "СКЛАД",
                   "order_no": "49-24.08.26", "counter_start": 21563900,
                   "counter_end": 21585100}],
        "events": [{"start": "07:00", "end": "07:40", "kind": "подмена",
                    "reason": "подмена", "performer": None},
                   {"start": "13:05", "end": "13:55", "kind": "подмена",
                    "reason": "подмена", "performer": None}],
    }
    # Проверка показаний идёт до расчёта — так же, как в сборке смены.
    from services.day_pipeline import _validate_counters, DayResult
    data = {"machines": [machine]}
    _validate_counters(data, "28.09.2026", DayResult("28.09.2026"))
    r = shift_report.build_shift_reports_from_structured(data)[0]
    assert int(r.lines[0].counter_start) == 21574050, r.lines[0].counter_start
    assert r.lines[0].output == 11050, r.lines[0].output
    assert abs(r.work_hours - 10.23) < 0.05, r.work_hours
    assert r.work_hours <= 12.0, r.work_hours


def test_первое_показание_оператора_сильнее_нового_пути():
    """21.09.2026, ст.98: у оператора своё показание есть — граница у него.

    Обратная проверка к новому правилу: оно не должно перетянуть начало на
    другое число темы там, где запись оператора надёжнее.
    """
    text = """98 машина(Белякова) - информация за смену 21.09.2026г.
Юлия Черныш, 06:38: Общий сч.21486750 Со.сч.1000 из 1450 Срез 4 .из 4
Белякова С., 06:53: 7.00 машина в работе Сч 21497900
Белякова С., 19:06: Общ. Счётчик 21509000 Всего 8 срезов 19.00 конец смены.
"""
    start, end, notes = cc.check_counters("98", 21486750, 21509000, text=text,
                                          operator="Белякова")
    assert int(start) == 21497900, (start, end, notes)
    assert any("утренней сводки" in n for n in notes), notes


