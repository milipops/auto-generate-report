"""Регрессии прогона 10.09.2026 (остатки сырья и сдаваемые отходы).

Что сломалось в реальном прогоне:

1. NFD-юникод. Из мессенджера слово «Общий» приходит как «Общи» + U+0306
   (combining breve). Поиск маркера «общий сч» не срабатывал, и конечное
   показание ст.251 (278755) терялось целиком.

2. Заголовок раздела «–251» стоял НЕ с начала строки: экспорт склеил абзацы
   («…выхода полотна. –251»). Секция 251-й не находилась, и ВСЕ её показания
   уезжали на №151.

3. Длинную переписку Telegram режет по 4096 знаков, и разрез попал
   ПОСЕРЕДИНЕ обсуждения 251-й: «–251» в первом сообщении, «Конец смены …
   278755» — во втором. Хвост без заголовка уходил в «станок не указан».

4. «7:00-7:07начало смены м прием ее» открывало ложный замер и рвало
   настоящие показания машины на два региона.

5. «Ср.сч 250узл. из 1400\n4 ср.» — _NUM_RE глотал перевод строки, матчилось
   «1400\n4», float() падал, «из 1400» терялось.

6. «Подмена 4 из 5» + «16:38 пуск» склеились в «из 516:38» — планом стало
   несуществующее число 516.

7. «10.05-10.55 подмена Навивка шпулей 250 из 250» (операция из таймлайна)
   читалось как показание «Подмена 250 из 250» вместо настоящих «4 из 1».

8. «Шпульный стол в работе» считался маркером вида отходов и отрезал
   показание «Шпуля: навито — 287 из 303».

9. «от разаивки 15 штук шпулей (половинок) = 2 кг» — опечатка мастера; 2 кг
   уходили в «вид отходов не назван» и пропадали из учёта.

10. «Состояние машины:» со списком на СЛЕДУЮЩИХ строках (ст.251: расширенные
    шпули, посторонний шум, перекос осадного вала, отклеилась лента) давало
    пустое поле — парсер брал только остаток текущей строки.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from services import remains_report as rr                       # noqa: E402


def _one(text, hint=None):
    blocks = rr.parse_blocks(text, machine_hint=hint)
    assert blocks, f"блок не собрался: {text[:80]!r}"
    return blocks[0]


def test_nfd_unicode_does_not_hide_the_counter():
    """NFD «Общий»/«Срезовой» (й = и + U+0306) больше не прячет показание.

    Форма — ровно та, что пришла в прогоне 10.09.2026: «Общи» + «и» + U+0306.
    """
    nfd_obshiy = "Общи" + "и\u0306"          # «Общий» в NFD
    nfd_srezovoy = "Срезово" + "и\u0306"     # «Срезовой» в NFD
    text = ("Конец смены- стоп машина:\n"
            f"* {nfd_obshiy} сч.: 278755\n"
            f"* {nfd_srezovoy} сч.: 4981 из 15900\n"
            "* Срез: 1 из 1\n* Подмена: 4 из 5")
    assert rr.normalize_text(nfd_obshiy) == "Общий"
    b = _one(text, "251")
    assert b.counter("общий_счётчик") == 278755.0, b.counters
    assert b.counter("средний_счётчик") == 4981.0, b.counters
    assert b.counter_of("средний_счётчик") == 15900.0, b.counters
    print("✅ NFD-юникод нормализуется, показание найдено")


def test_section_header_not_at_line_start():
    """«…полотна. –251» — заголовок раздела после склейки абзацев."""
    text = ("Перегорели лампы освещения в кол-ве 6 шт со стороны выхода "
            "полотна. –251\nЮлия Черныш, 16:57:Навито 226 из 303 шт. шпулей\n"
            "Об. Сч.: 274659\nСр. Сч.: 885 из 15900\nСрез 1 из 1\n")
    heads = rr._section_head_positions(text)
    assert [n for _p, n in heads] == ["251"], heads
    blocks = {b.machine: b for b in rr.parse_blocks(text, machine_hint="151")}
    assert "251" in blocks, sorted(blocks)
    assert blocks["251"].counter("общий_счётчик") == 274659.0
    print("✅ заголовок раздела находится и не с начала строки")


def test_counter_value_is_not_a_section_header():
    """«Общ.сч. - 100» и «Ср.сч. - 251» — значения, а не станки."""
    assert rr._is_section_head("Общ.сч. - 100",
                               rr._SECTION_HEAD_RE.search("Общ.сч. - 100")) is False
    b = _one("Конец смены машина 151:\nОбщ.сч. - 100\nСр.сч. - 251 из 900\n"
             "Срез - 1 из 2")
    assert b.machine == "151", b.machine
    assert b.counter("общий_счётчик") == 100.0, b.counters
    assert b.counter("средний_счётчик") == 251.0, b.counters
    print("✅ значение показания станком не считается")


def test_tail_of_split_message_keeps_its_machine():
    """Разрез посередине обсуждения: хвост второго сообщения — тому же станку."""
    msgs = [
        {"index": 1, "text": "–151\nОбщ.сч. - 750733\nСр.сч. - 5042 из 14500\n"
                             "Срез - 1 из 1\nПодмена - 2 из 4\n"
                             "Перегорели лампы. –251\nНавито 226 из 303\n"
                             "Об. Сч.: 274659\nСр. Сч.: 885 из 15900"},
        {"index": 2, "text": "После обеда продолжим мониторинг.\n"
                             "Конец смены- стоп машина:\n"
                             "* Общий сч.: 278755\n* Срезовой сч.: 4981 из 15900\n"
                             "* Срез: 1 из 1\n* Подмена: 4 из 5\n"
                             "Шпульный стол в работе . Шпуля:\n"
                             "навито — 287 из 303, развито — 0 из 0\n"
                             "Состояние машины:\n* Полотна чистые.\n"
                             "Сдаваемые отходы:\nот разаивки 15 штук шпулей "
                             "(половинок) = 2 кг."},
    ]
    day = rr.build_day_remains("10.09.2026", messages=msgs)
    b151, b251 = day.by_machine("151"), day.by_machine("251")
    assert b151 and b251, [b.machine for b in day.machines]
    assert b151.counter("общий_счётчик") == 750733.0, b151.counters
    assert b251.counter("общий_счётчик") == 278755.0, b251.counters
    assert b251.counter("шпуля_навито") == 287.0, b251.counters
    assert day.warnings == [], day.warnings
    print("✅ хвост разрезанного сообщения отнесён к своему станку")


def test_glued_words_do_not_open_a_fake_reading():
    """«07:07начало смены» — не заголовок замера."""
    assert rr._HEAD_RE.search("07:07начало смены м прием ее") is None
    assert rr._HEAD_RE.search("7:00 начало смены") is not None
    assert rr._HEAD_RE.search("19:00 Конец смены:") is not None
    print("✅ склейка времени со словами «начало смены» замер не открывает")


def test_newline_is_not_part_of_a_number():
    """«из 1400\n4 ср.» — план 1400, а не «14004»."""
    b = _one("Конец смены машина 98:\nОбщ.сч 21387950\nСр.сч 250узл. из 1400\n"
             "4 ср. из.4 ср.\nНавито 250шп. из 250шп.")
    assert b.counter("средний_счётчик") == 250.0, b.counters
    assert b.counter_of("средний_счётчик") == 1400.0, b.counters
    assert b.counter("срез") == 4.0, b.counters
    print("✅ перевод строки не склеивается с числом")


def test_time_after_the_plan_is_not_a_plan():
    """«Подмена 4 из 5» + «16:38 пуск» → 4 из 5, а не 4 из 516."""
    assert rr._split_of(" 4 из 516:38 пуск") == (4.0, None)
    b = _one("Конец смены:\nоб. сч.:277761\nСр. Сч. 3987 из 15900\n"
             "Срез 1 из 1\nПодмена 4 из 516:38 пуск", "251")
    assert b.counter("подмена") == 4.0, b.counters
    assert b.counter_of("подмена") is None, b.counters
    print("✅ время пуска не стало планом подмен")


def test_operation_word_without_a_value_is_not_a_reading():
    """«10.05-10.55 подмена Навивка шпулей 250 из 250» — операция, не показание."""
    b = _one("Конец смены машина 98:\n10.05-10.55 подмена Навивка шпулей 250 из 250\n"
             "Общ.сч 21387950\nСр.сч 250узл. из 1400\n4 ср. из.4 ср.\n"
             "Подмена - 1 из 1\nНавито 250шп. из 250шп.")
    assert b.counter("подмена") == 1.0, b.counters
    assert b.counter_of("подмена") == 1.0, b.counters
    print("✅ слово «подмена» без значения показанием не считается")


def test_spool_table_in_work_is_not_waste_kind():
    """«Шпульный стол в работе» не режет показания и не становится видом отходов."""
    b = _one("Конец смены- стоп машина:\n* Общий сч.: 278755\n"
             "* Срезовой сч.: 4981 из 15900\n* Срез: 1 из 1\n* Подмена: 4 из 5\n"
             "Шпульный стол в работе . Шпуля:\nнавито — 287 из 303, "
             "развито — 0 из 0\nСостояние машины:\n* Полотна чистые.", "251")
    assert b.counter("шпуля_навито") == 287.0, b.counters
    assert b.counter("шпуля_развито") == 0.0, b.counters
    assert b.has_waste is False, b.waste
    print("✅ «Шпульный стол в работе» отходами не считается")


def test_typo_razavivka_is_still_counted():
    """«от разаивки … = 2 кг» (опечатка мастера) — это развивка шпулей."""
    b = _one("Сдаваемые отходы:\nот разаивки 15 штук шпулей (половинок) = 2 кг.", "251")
    assert b.waste.get("развивка_шпулей") == 2.0, b.waste
    assert b.waste_total == 2.0
    print("✅ опечатка «разаивки» прочитана как развивка шпулей")


def test_state_written_as_a_list_is_kept():
    """«Состояние машины:» со списком на следующих строках не теряется."""
    b = _one("Состояние машины:\n* Полотна чистые, без обрывов и дыр.\n"
             "* Необходимо решить, что делать с расширенными шпулями.\n"
             "* Следует обратить внимание на посторонний шум.\n"
             "* отклеилась лента .\nСдаваемые отходы:\nНаладочные - 1кг", "251")
    assert "Полотна чистые" in b.state, b.state
    assert "посторонний шум" in b.state, b.state
    assert "отклеилась лента" in b.state, b.state
    assert "Сдаваемые отходы" not in b.state, b.state
    print("✅ состояние машины списком собрано целиком")


def test_state_in_one_line_still_works():
    """Прежняя форма «Состояние … : текст» читается как раньше."""
    b = _one("Состояние машины и полотна: Машина в рабочем состоянии.\n"
             "Сдаваемые отходы:\nНаладочные - 1кг", "151")
    assert b.state == "Машина в рабочем состоянии", b.state
    print("✅ состояние одной строкой читается как раньше")


