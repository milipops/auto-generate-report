    r = _machine()
    srez = [s for s in r.tech_stops
            if (s.reason or "").startswith("стоп машина на срез")]
    assert srez, [s.reason for s in r.tech_stops]
    assert (srez[0].start_min, srez[0].end_min) == (17 * 60 + 20, 17 * 60 + 30), \
        (srez[0].start_min, srez[0].end_min)


