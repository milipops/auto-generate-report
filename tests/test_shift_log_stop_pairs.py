# ——— 1. окно «стоп → пуск» строится по переписке своей машины ———

def test_stop_and_pusk_pairs_make_windows():
    windows = sr._log_stop_windows(REAL_321_LOG, "321")
    assert [(s, e) for s, e, _ in windows] == [
        (15 * 60 + 21, 15 * 60 + 50),   # 15:21 стоп → 15:50 пуск
        (16 * 60 + 1, 16 * 60 + 17),    # 16:01 стоп → 16:17 пуск
        (17 * 60 + 20, 18 * 60 + 33),   # 17:20 стоп (+17:30 подробнее) → 18:33 пуск
    ], [(sr._log_hm(s), sr._log_hm(e)) for s, e, _ in windows]


def test_repeated_stop_inside_open_window_extends_text_not_windows():
    """«17:20 стоп на срез» и «17:30 в стопе замена катушек» — одна остановка."""
