# ——— 5. пара «чинка …» → «вычинил»: станок стоял, и мастер это написал ———
#
# Вопрос пользователя от 29.09.2026 по ст.321 за смену 28.09.2026: «в отчёте они
# идут без времени, а я просил вычислять время из начала работ и конца:
# 2026-09-28 07:04:55 Олег „Чинка пропуска на 3 полотне“,
# 2026-09-28 07:19:06 Олег „Вычинил“».
#
# Слова «стоп» и «пуск» в этой паре нет вообще: операцию, которую не делают на
# ходу, открывает останов, а то же слово, сказанное в прошедшем времени, его
# закрывает.

REAL_321_FIX_LOG = """Олег, 06:50: Общ.сч. -__126174____ Ср.сч. - ___31__ из__760__ Срез - _2__ из __2__
Олег, 07:04: Чинка пропуска на 3 полотне [медиа]
Олег, 07:19: Вычинил [медиа]
Олег, 07:20: Чинка пропуска на 3 полотне [медиа]
Олег, 07:35: Вычинил [медиа]
Олег, 07:36: Чинка пропуска 3 полотна [медиа]
Олег, 07:48: Вычинил [медиа]
Олег, 08:05: Пуск
"""


def test_chinka_pair_makes_a_window():
    """«07:04 Чинка пропуска» → «07:19 Вычинил» = 15 минут простоя станка."""
    windows = sr._log_stop_windows(REAL_321_FIX_LOG, "321")
    assert [(sr._log_hm(s), sr._log_hm(e)) for s, e, _ in windows] == [
        ("07:04", "07:19"), ("07:20", "07:35"), ("07:36", "07:48")], windows


def test_chinka_pair_gives_hours_to_an_event_without_end():
    """ИИ отдал по такому событию только начало — конец доводит код."""
    r = _machine(log=REAL_321_FIX_LOG, events=[
        {"start": "07:04", "end": None, "kind": "чинка",
         "reason": "чинка пропуска на 3 полотне"}])
    row = [s for s in r.tech_stops
           if (s.reason or "").startswith("чинка пропуска")]
    assert row, [s.reason for s in r.tech_stops]
    assert (row[0].start_min, row[0].end_min) == (7 * 60 + 4, 7 * 60 + 19)
    assert row[0].hours == 0.25, row[0].hours
    assert "07:04–07:19" in " ".join(r.log_timed_stops), r.log_timed_stops


