def test_schjotchikovaja_stroka_prichinoj_ne_stanovitsja():
    """«2 срез-731 узлов- сч-304851» — это состояние, а не причина простоя.

    Из такой строки берётся только время; называть её причиной код не должен,
    иначе в отчёте появится простая запись показаний.
    """
    assert sr._log_is_counter_report(
        "2 срез, 731 узлов, общ.сч 304851, срез.сч 731")
    assert not sr._log_is_counter_report(
        "убавлена подача помогающего вала, нити на бабинах мала")
    event = dict(UNTIMED_VAL_EVENT,
                 reason="2 срез-731 узлов- сч-304851. Общ.ся-304851")
    r = _machine_251(COUNTER_FREEZE_LOG_251, [event])
    assert not any("304851" in (s.reason or "") for s in r.tech_stops), \
        [s.reason for s in r.tech_stops]


def test_minuty_uhoda_operatora_povtorno_ne_nazyvajutsja():
    """Часы ухода на 111 уже объяснены — отнять их у этой строки нельзя.

    Вечер 28.09, ст.251: «12:24 Продолжаю навивку шпулей на 111». Его минуты
    уже стоят в строке ухода, и новое окно должно остановиться на 12:20.
    """
    elsewhere = {"start": "12:20", "end": "18:50", "kind": "навивка",
                 "reason": "продолжаю навивку шпулей на 111",
                 "performer": None, "other_machine": "111", "hours": 4.0}
    base, named = _with_rule_off(
        lambda: _machine_251(COUNTER_FREEZE_LOG_251,
                             [UNTIMED_VAL_EVENT, elsewhere]))
    assert named.work_hours == base.work_hours
    assert named.machine_downtime == base.machine_downtime
    row = [s for s in named.tech_stops if "помогающего вала" in (s.reason or "")]
    assert len(row) == 1, [s.reason for s in named.tech_stops]
    assert row[0].end_min == 12 * 60 + 20, sr._log_hm(row[0].end_min)
    gone = [s for s in base.tech_stops if s.other_machine == "111"]
    grew = [s for s in named.tech_stops if s.other_machine == "111"]
    assert sum(s.hours for s in gone) == sum(s.hours for s in grew)
